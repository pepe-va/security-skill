#!/usr/bin/env python3
"""Generate references/standards/nist-csf-2.0.md from the NIST CPRT export of CSF 2.0.

The CPRT export carries the 6 functions, the categories and subcategories (active and withdrawn
from CSF 1.1, with the reason), the implementation examples, and informative references from
subcategories to SP 800-53 Rev. 5.1.1, which this file keeps as the bridge to the 800-53 catalogue.

Stdlib only.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
SRC = SOURCES / "csf" / "csf-2.0.0.json"
OUT = SKILL / "references" / "standards" / "nist-csf-2.0.md"
CPRT = "https://csrc.nist.gov/extensions/nudp/services/json/nudp/framework/version/csf_2_0_0/export/json?element=all"
ORDER = ["GV", "ID", "PR", "DE", "RS", "RC"]


def key(i):
    return [int(p) if p.isdigit() else p for p in re.split(r"(\d+)", i)]


def main():
    d = json.loads(SRC.read_text(encoding="utf-8"))["response"]["elements"]
    doc = d["documents"][0]
    els = {e["element_identifier"]: e for e in d["elements"]}
    kids, refs53 = {}, {}
    for r in d["relationships"]:
        s, t, k = r["source_element_identifier"], r["dest_element_identifier"], r["relationship_identifier"]
        if k == "projection" and t in els and els[t]["element_type"] != "sort":
            kids.setdefault(s, []).append(t)
        elif k == "external_reference" and r["dest_doc_identifier"].startswith("SP_800_53"):
            refs53.setdefault(s, set()).add(t)
    withdrawn = {e: els[f"WR-{e}"]["text"] for e in els if f"WR-{e}" in els}
    functions = [els[f] for f in ORDER]
    cats = {f: sorted((c for c in kids.get(f, []) if els[c]["element_type"] == "category"), key=key) for f in ORDER}
    active_cats = [c for f in ORDER for c in cats[f] if c not in withdrawn]
    subs_of = {c: sorted((s for s in kids.get(c, []) if els[s]["element_type"] == "subcategory"), key=key)
               for f in ORDER for c in cats[f]}
    active_subs = [s for c in active_cats for s in subs_of[c] if s not in withdrawn]
    examples = sum(len([x for x in kids.get(s, []) if els[x]["element_type"] == "implementation_example"]) for s in active_subs)

    L = []
    w = L.append
    w("# NIST Cybersecurity Framework (CSF) 2.0")
    w("")
    w(f"**Normative source:** {doc['name']}, {doc['version'].replace('  ', ' ')} (NIST CSWP 29, February 2024) · "
      f"{doc['website']}")
    w("")
    w(f"**Machine-readable source (CPRT):** {CPRT}")
    w("")
    w(f"**Contents:** {len(functions)} functions · {len(active_cats)} categories · {len(active_subs)} subcategories · "
      f"{examples} implementation examples · informative references to SP 800-53 Rev. 5.1.1 · "
      f"{len(withdrawn)} CSF 1.1 identifiers withdrawn (listed at the end).")
    w("")
    w("> Generated by `scripts/gen_csf.py` from the NIST CPRT export. Do not edit by hand: regenerate.")
    w("")
    w("## Purpose in this skill")
    w("")
    w("CSF 2.0 describes **organisational cybersecurity outcomes**, not technical requirements of a system. Use it to "
      "place a finding or a programme gap in the organisation's posture (GOVERN, IDENTIFY, PROTECT, DETECT, RESPOND, "
      "RECOVER), to talk to governance and audit audiences, and to reach SP 800-53 controls through the informative "
      "references. Nearly every playbook of Anthropic-Cybersecurity-Skills carries `nist_csf` subcategories.")
    w("")
    w("## Reading rules")
    w("")
    w("- Subcategories are **outcomes**, deliberately technology-neutral. PASS / FAIL against a subcategory needs "
      "organisational evidence (policy, process, records); a code finding alone rarely decides one. Prefer "
      "**NOT VERIFIED** with the evidence that would decide it.")
    w("- **Implementation examples are illustrative**, not requirements. Never turn one into an obligation.")
    w("- Cite subcategories as `PR.AA-05 (CSF 2.0)`. Identifiers withdrawn from CSF 1.1 must not be cited; use the "
      "destination given in the withdrawn list.")
    w("- The SP 800-53 references are **informative** (NIST's own mapping); the 800-53 control text is in "
      "`nist-800-53r5/`. CSF does not replace the verifiable control.")
    w("")
    w("## Index")
    w("")
    for f in functions:
        fid = f["element_identifier"]
        w(f"- **{f['title']} ({fid})** — " + " · ".join(
            f"{c} {els[c]['title']}" for c in cats[fid] if c not in withdrawn))
    w("")
    for f in functions:
        fid = f["element_identifier"]
        w(f"## {f['title']} ({fid})")
        w("")
        w("> " + f["text"].strip())
        w("")
        for c in cats[fid]:
            if c in withdrawn:
                continue
            ce = els[c]
            w(f"### {c} — {ce['title']}")
            w("")
            if ce["text"].strip():
                w("> " + ce["text"].strip())
                w("")
            for s in subs_of[c]:
                if s in withdrawn:
                    continue
                w(f"#### {s}")
                w("")
                w("> " + els[s]["text"].strip())
                w("")
                exs = sorted((x for x in kids.get(s, []) if els[x]["element_type"] == "implementation_example"), key=key)
                if exs:
                    w("*Implementation examples:*")
                    w("")
                    for x in exs:
                        w(f"- {els[x]['title'].strip() or '—'}: {' '.join(els[x]['text'].split())}")
                    w("")
                if s in refs53:
                    w("*SP 800-53 Rev. 5.1.1 (informative):* " + ", ".join(sorted(refs53[s], key=key)))
                    w("")
    w("## Identifiers withdrawn from CSF 1.1")
    w("")
    w("| Identifier | Reason |")
    w("|---|---|")
    for e in sorted(withdrawn, key=key):
        w(f"| {e} | {withdrawn[e]} |")
    w("")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {len(functions)} functions, {len(active_cats)} categories, {len(active_subs)} subcategories, "
          f"{examples} examples, {len(withdrawn)} withdrawn", file=sys.stderr)


if __name__ == "__main__":
    main()
