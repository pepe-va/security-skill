#!/usr/bin/env python3
"""Generate the official ASI crosswalk references and verify their identifiers."""

from __future__ import annotations

import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPO = "https://github.com/GenAI-Security-Project/crosswalk"
ENTRIES = REPO + "/blob/main/data/entries"
LICENSE = "CC BY-SA 4.0 — OWASP GenAI Data Security Initiative"

RISKS = [f"ASI{n:02d}" for n in range(1, 11)]

# Standards whose authoritative text this skill holds: their identifiers can be checked
# file against file. Value: (glob(s) under references/standards/, matching mode).
VALIDATED = {
    "OWASP ASVS 5.0.0": (("owasp-asvs-5.0.0.md",), "id"),
    "NIST SP 800-218A": (("nist-800-218a.md",), "id-without-suffix"),
    "MITRE ATLAS": (("mitre-atlas.md", "mitre-atlas-case-studies.md"), "id"),
    "OWASP SAMM v2.0": (("owasp-samm-2.0.md",), "practice-name"),
    "NIST CSF 2.0": (("nist-csf-2.0.md",), "id"),
    "NIST AI RMF 1.0": (("nist-ai-rmf-1.0.md",), "ai-rmf-short-form"),
    "CWE/CVE": (("cwe/*.md",), "cwe-only"),
    "FedRAMP": (("nist-800-53r5/*.md",), "sp800-53-control"),
}
AI_RMF_FUNCTIONS = {"GV": "GOVERN", "MP": "MAP", "MS": "MEASURE", "MG": "MANAGE"}

# SC controls this skill associates with each ASI risk. Editorial mapping: the only
# link of the chain that does not come from an official source.
SC_BY_RISK = {
    "ASI01": ["SC-AI-01", "SC-AI-02", "SC-AI-03", "SC-IN-01", "SC-IN-03"],
    "ASI02": ["SC-AI-02", "SC-AI-03", "SC-AI-07", "SC-AI-08", "SC-AUTH-03"],
    "ASI03": ["SC-AI-02", "SC-AUTH-01", "SC-AUTH-02", "SC-AUTH-03"],
    "ASI04": ["SC-SUP-01", "SC-SUP-02", "SC-SUP-03", "SC-AI-09"],
    "ASI05": ["SC-AI-02", "SC-AI-07", "SC-AI-08", "SC-SEC-01", "SC-SEC-02"],
    "ASI06": ["SC-AI-04", "SC-AI-05", "SC-AI-06", "SC-IN-02"],
    "ASI07": ["SC-AI-02", "SC-AI-10", "SC-TLS-01", "SC-IN-02"],
    "ASI08": ["SC-AI-03", "SC-AI-08", "SC-CFG-01", "SC-OUT-01"],
    "ASI09": ["SC-AI-03", "SC-AI-06", "SC-AI-07", "SC-AI-09", "SC-LOG-01", "SC-LOG-02"],
    "ASI10": ["SC-AI-09", "SC-AI-10", "SC-VER-02", "SC-LOG-02"],
}


def load(source: Path) -> dict[str, dict]:
    """Load the ten crosswalk entries."""
    out = {}
    for rid in RISKS:
        path = source / f"{rid}.json"
        if not path.exists():
            sys.exit(f"missing {path}\ndownload it from {ENTRIES}/{rid}.json")
        out[rid] = json.loads(path.read_text(encoding="utf-8"))
    return out


def standards_text(root: Path) -> dict[str, str]:
    """Read the standard files used to verify identifiers; absent standards are skipped."""
    base = root / "references" / "standards"
    texts = {}
    for framework, (globs, _) in VALIDATED.items():
        files = [f for g in globs for f in sorted(base.glob(g))]
        if files:
            texts[framework] = "".join(f.read_text(encoding="utf-8") for f in files)
        else:
            print(f"note: {framework} not generated yet; its identifiers are left unverified", file=sys.stderr)
    return texts


def check(mapping: dict, texts: dict[str, str]) -> bool | None:
    """Return whether the crosswalk identifier exists in the local standard (None if unverifiable)."""
    framework = mapping["framework"]
    if framework not in texts:
        return None
    body = texts[framework]
    mode = VALIDATED[framework][1]
    needle = mapping["control_id"].strip()
    if mode == "practice-name":
        needle = mapping["control_name"].split("/")[-1].strip()
        return bool(re.search(re.escape(needle), body, re.I))
    if mode == "id-without-suffix":
        needle = re.sub(r"-PS$", "", needle)
    elif mode == "ai-rmf-short-form":
        m = re.fullmatch(r"(GV|MP|MS|MG)-(\d+\.\d+)", needle)
        if not m:
            return False
        needle = f"{AI_RMF_FUNCTIONS[m.group(1)]} {m.group(2)}"
    elif mode == "cwe-only":
        if not needle.startswith("CWE-"):
            return None  # CVE rows are incident references, not part of the CWE catalogue
    elif mode == "sp800-53-control":
        needle = re.sub(r"\s+", "", needle).upper()
    return bool(re.search(r"(?<![\w.-])" + re.escape(needle) + r"(?![\w-])", body))


def cell(text: str | None) -> str:
    """Make text safe for a markdown table cell."""
    return (text or "").replace("|", "\\|").replace("\n", " ").strip() or "—"


def verdict(ok: bool | None) -> str:
    return {True: "yes", False: "**no**", None: "—"}[ok]


def risk_page(rid: str, entry: dict, texts: dict[str, str]) -> str:
    by_framework: dict[str, list[dict]] = defaultdict(list)
    for mapping in entry["mappings"]:
        by_framework[mapping["framework"]].append(mapping)

    lines = [
        f"# Official crosswalk — {rid} {entry['name']}",
        "",
        "> Generated by `scripts/gen_crosswalk.py`. Do not edit by hand: regenerate.",
        "",
        f"- **Entry:** `{ENTRIES}/{rid}.json`",
        f"- **Crosswalk version:** {entry.get('version', 'unversioned')}",
        f"- **Declared severity:** {entry.get('severity', '—')}"
        f" · **AIVSS:** {entry.get('aivss_score', '—')}",
        f"- **Mappings:** {len(entry['mappings'])} across {len(by_framework)} frameworks",
        f"- **Licence:** {LICENSE}",
        "",
        "> **Every crosswalk mapping is marked `confidence: unreviewed`.**",
        "> It is a navigation hint, not an authority: the compliance criterion is still the",
        "> original requirement. See `README.md` in this folder.",
        "",
        f"**Risk in the standard:** `../standards/owasp-asi-top10-2026.md` → {rid}.",
        f"**Associated SC controls (editorial):** {', '.join(SC_BY_RISK[rid])}.",
        "",
    ]

    cross = entry.get("crossrefs") or {}
    if cross.get("llm_top10"):
        lines += [f"**Related LLM Top 10 (crosswalk):** {', '.join(cross['llm_top10'])}.", ""]

    for framework in sorted(by_framework):
        rows = by_framework[framework]
        lines += [f"## {framework}", ""]
        if framework in texts:
            resolved = sum(1 for row in rows if check(row, texts))
            checkable = sum(1 for row in rows if check(row, texts) is not None)
            lines += [
                f"*Identifiers verified against the local standard: {resolved}/{checkable}.*",
                "",
                "| ID | Control | Tier | Scope | Crosswalk note | Resolves |",
                "|---|---|---|---|---|---|",
            ]
            for row in rows:
                lines.append(
                    f"| `{cell(row['control_id'])}` | {cell(row['control_name'])} "
                    f"| {cell(row.get('tier'))} | {cell(row.get('scope'))} "
                    f"| {cell(row.get('notes'))} | {verdict(check(row, texts))} |"
                )
        else:
            lines += [
                "| ID | Control | Tier | Scope | Crosswalk note |",
                "|---|---|---|---|---|",
            ]
            for row in rows:
                lines.append(
                    f"| `{cell(row['control_id'])}` | {cell(row['control_name'])} "
                    f"| {cell(row.get('tier'))} | {cell(row.get('scope'))} "
                    f"| {cell(row.get('notes'))} |"
                )
        lines.append("")

    if entry.get("tools"):
        lines += ["## Tools the crosswalk associates with the risk", ""]
        for tool in entry["tools"]:
            lines.append(f"- [{tool['name']}]({tool['url']}) — {tool.get('type', '')}")
        lines.append("")

    if entry.get("incidents"):
        lines += [
            "## Incidents the crosswalk associates with the risk",
            "",
            "| Year | ID | Incident |",
            "|---|---|---|",
        ]
        for inc in sorted(entry["incidents"], key=lambda i: -(i.get("year") or 0)):
            lines.append(
                f"| {inc.get('year', '—')} | `{inc.get('incident_id', '—')}` "
                f"| [{cell(inc['name'])}]({inc.get('url', REPO)}) |"
            )
        lines.append("")

    return "\n".join(lines) + "\n"


def readme(entries: dict[str, dict], texts: dict[str, str], stats: dict) -> str:
    frameworks = sorted({m["framework"] for e in entries.values() for m in e["mappings"]})
    total = sum(len(e["mappings"]) for e in entries.values())
    verified = [f for f in VALIDATED if f in texts]

    lines = [
        "# Official crosswalk of the OWASP Top 10 for Agentic Applications",
        "",
        "> Generated by `scripts/gen_crosswalk.py`. Do not edit by hand: regenerate.",
        "",
        f"- **Repository:** {REPO}",
        f"- **Version:** {stats.get('version', 'unversioned')}",
        f"- **Licence:** {LICENSE}",
        f"- **Scope incorporated:** the ten ASI risks — {total} mappings across {len(frameworks)} frameworks.",
        "",
        "## What it is for, and what it is not",
        "",
        "The crosswalk supplies the **ASI risk → control in another framework** link with official",
        "provenance, instead of a hand-made mapping. It replaces manual work on that link.",
        "",
        "What does **not** change:",
        "",
        "1. **No crosswalk mapping is reviewed.** All rows carry `confidence: unreviewed` and",
        "   `reviewed_by: []`; some carry a `DRAFT` warning in the note. Official provenance is",
        "   not the same as reviewed content.",
        "2. **The compliance criterion is still the original requirement.** The crosswalk says",
        "   *look there*; what is required is stated by the standard, in its file under",
        "   `../standards/`.",
        "3. **The SC control → ASI risk link stays editorial.** The crosswalk does not know the",
        "   SC controls. The full chain is: SC control → ASI risk (editorial) → framework control",
        "   (crosswalk, unreviewed) → requirement (authoritative).",
        "",
        "## Identifier verification",
        "",
        f"This skill holds the authoritative text of {len(verified)} of the crosswalk frameworks, so",
        "their identifiers were checked file against file:",
        "",
        "| Framework | Rows | Checkable | Resolve | Criterion |",
        "|---|---|---|---|---|",
    ]

    exceptions: list[str] = []
    for framework in verified:
        mode = VALIDATED[framework][1]
        rows = [m for e in entries.values() for m in e["mappings"] if m["framework"] == framework]
        checkable = [m for m in rows if check(m, texts) is not None]
        ok = [m for m in checkable if check(m, texts)]
        lines.append(f"| {framework} | {len(rows)} | {len(checkable)} | {len(ok)} | {mode} |")
        for e in entries.values():
            for m in e["mappings"]:
                if m["framework"] == framework and check(m, texts) is False:
                    exceptions.append(f"{e['id']} · {framework} · `{m['control_id']}` — {m['control_name']}")
    lines.append("")

    if exceptions:
        lines += ["**Exceptions found** (identifier absent from the local standard):", ""]
        lines += [f"- {line}" for line in sorted(set(exceptions))]
        lines.append("")
    else:
        lines += ["No exceptions: every checkable identifier resolves.", ""]

    lines += [
        "Notation details of the crosswalk, not errors:",
        "",
        "- **SP 800-218A** identifiers carry a `-PS` suffix (`PW.2.1-PS`). The suffix belongs to the",
        "  crosswalk; the NIST task is `PW.2.1`.",
        "- **SAMM** uses practice abbreviations (`D-TA`, `V-ST`, `O-IM`) that are not SAMM",
        "  identifiers. The practice is resolved through `control_name` (*Design / Threat Assessment*).",
        "- **AI RMF** uses a short form (`GV-1.7`); the standard writes `GOVERN 1.7`.",
        "- **CWE/CVE** mixes weaknesses and vulnerabilities; only the `CWE-*` rows are checkable",
        "  against the CWE catalogue.",
        "- **FedRAMP** rows are NIST SP 800-53 control identifiers and are checked against 800-53 Rev. 5.",
        "",
        f"The remaining {len(frameworks) - len(verified)} frameworks are reproduced as they are: this skill",
        "does not hold their text and cannot verify them. Treat their rows as hints, never as",
        "requirements. Their tier is in `../standards/INVENTORY.md`.",
        "",
        "## Mappings per framework and risk",
        "",
        "| Framework | " + " | ".join(r[3:] for r in RISKS) + " | Total | Verified |",
        "|---" * (len(RISKS) + 3) + "|",
    ]
    counts = {rid: Counter(m["framework"] for m in entries[rid]["mappings"]) for rid in RISKS}
    for framework in frameworks:
        row = " | ".join(str(counts[rid].get(framework, 0) or "·") for rid in RISKS)
        mark = "yes" if framework in texts else "—"
        total_fw = sum(counts[rid].get(framework, 0) for rid in RISKS)
        lines.append(f"| {framework} | {row} | {total_fw} | {mark} |")
    pages = " | ".join(f"[{rid[3:]}]({rid}.md)" for rid in RISKS)
    lines += [f"| **Risk page** | {pages} | {total} | |", ""]

    lines += [
        "## Inverse index: SC control → ASI risk → crosswalk",
        "",
        "Editorial link. From an SC control, leads to the ASI risks whose crosswalk extends its",
        "traceability.",
        "",
        "| SC control | ASI risks |",
        "|---|---|",
    ]
    inverse: dict[str, list[str]] = defaultdict(list)
    for rid, controls in SC_BY_RISK.items():
        for control in controls:
            inverse[control].append(rid)
    for control in sorted(inverse):
        links = " · ".join(f"[{rid}]({rid}.md)" for rid in sorted(inverse[control]))
        lines.append(f"| `{control}` | {links} |")
    lines.append("")

    lines += [
        "## How to regenerate",
        "",
        "```",
        f"# download data/entries/ASI01..ASI10.json and data/stats.json from {REPO}",
        "# into sources/crosswalk/ and run:",
        "python scripts/gen_crosswalk.py",
        "```",
        "",
        "Run it after the standard generators, so that every verifiable framework is present.",
        "",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    scripts = Path(__file__).resolve().parent
    root = scripts.parent / "skills" / "security" / "cybersec-skill"
    source = scripts.parent / "sources" / "crosswalk"
    entries = load(source)
    texts = standards_text(root)
    stats = json.loads((source / "stats.json").read_text(encoding="utf-8"))

    target = root / "references" / "crosswalk"
    target.mkdir(parents=True, exist_ok=True)
    (target / "README.md").write_text(readme(entries, texts, stats), encoding="utf-8")
    for rid in RISKS:
        (target / f"{rid}.md").write_text(risk_page(rid, entries[rid], texts), encoding="utf-8")
    total = sum(len(e["mappings"]) for e in entries.values())
    print(f"crosswalk: README + {len(RISKS)} risk pages, {total} mappings")


if __name__ == "__main__":
    main()
