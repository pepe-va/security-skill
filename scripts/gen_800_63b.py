#!/usr/bin/env python3
"""Generate references/standards/nist-800-63b-4.md from the official single-page NIST SP 800-63B-4.

Source: https://pages.nist.gov/800-63-4/sp800-63b.html (fetch_sources.py, group "800-63b"). The page
numbers its headings with CSS counters seeded by data-section; this generator rebuilds the same
numbers (3.1.1.2 ...) so requirements can be cited. Chapters 1-8 and appendices A-B are kept; the
references, glossary and change log are dropped. Requires beautifulsoup4, lxml and markdownify.
"""
import pathlib, re, sys

from bs4 import BeautifulSoup
from markdownify import markdownify

ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
SRC = SOURCES / "nist-800-63b-4" / "sp800-63b.html"
OUT = SKILL / "references" / "standards" / "nist-800-63b-4.md"
URL = "https://pages.nist.gov/800-63-4/sp800-63b.html"
DOI = "https://doi.org/10.6028/NIST.SP.800-63B-4"
KEEP = {"1", "2", "3", "4", "5", "6", "7", "8", "A", "B"}


def main():
    soup = BeautifulSoup(SRC.read_text(encoding="utf-8"), "lxml")
    for tag in soup.select("script, style, nav, header, footer, #search-box, #results-container"):
        tag.decompose()
    heads = soup.find_all(["h1", "h2", "h3", "h4", "h5"], attrs={"data-section": True})
    first = heads[0]
    container = first.parent
    counters = [0, 0, 0, 0]
    chapter = None
    numbered = 0
    for h in heads:
        level = int(h.name[1])
        sec = h["data-section"]
        if level == 1:
            chapter, counters = sec, [0, 0, 0, 0]
            num = f"{sec}." if sec.isdigit() else f"Appendix {sec}."
        else:
            counters[level - 2] += 1
            for i in range(level - 1, 4):
                counters[i] = 0
            num = ".".join([chapter] + [str(c) for c in counters[: level - 1]]) + "."
        text = h.get_text(" ", strip=True)
        h.clear()
        h.append(f"{num} {text}")
        h["data-keep"] = "1" if chapter in KEEP else "0"
        numbered += 1

    parts, keep = [], False
    for node in container.children:
        if getattr(node, "name", None) == "h1" and node.has_attr("data-section"):
            keep = node["data-keep"] == "1"
        if keep and getattr(node, "name", None):
            parts.append(str(node))
    if not parts:
        sys.exit("no content extracted; the page structure changed")
    md = markdownify("".join(parts), heading_style="ATX", bullets="-")
    md = re.sub(r"^(#{1,5}) ", lambda m: "#" * (len(m.group(1)) + 1) + " ", md, flags=re.M)
    md = re.sub(r"\]\((?!https?:)([^)]*)\)",
                lambda m: f"]({URL}" + (m.group(1)[m.group(1).index('#'):] if "#" in m.group(1) else "") + ")", md)
    md = re.sub(r"\n{3,}", "\n\n", md).strip()
    shall = len(re.findall(r"\bSHALL\b", md))

    L = [
        "# NIST SP 800-63B-4 — Digital Identity Guidelines: Authentication and Authenticator Management",
        "",
        f"**Official source:** {DOI} · **Web version used:** {URL}",
        "",
        f"**Contents:** chapters 1-8 and appendices A-B, with the official section numbers · {shall} `SHALL` statements.",
        "",
        "> Generated by `scripts/gen_800_63b.py` from the official web version. Section numbers are rebuilt from the "
        "page's own numbering scheme. References, glossary and change log are omitted. Do not edit by hand: "
        "regenerate.",
        "",
        "## Purpose in this skill",
        "",
        "SP 800-63B is the **authentication standard**: authentication assurance levels (AAL1-3), authenticator "
        "types, password and verifier rules, reauthentication and session management. Use it for any login, "
        "password, MFA, passkey, recovery or session design. Normative words follow NIST usage: **SHALL** / **SHALL "
        "NOT** are requirements, **SHOULD** recommendations, **MAY** permissions. Cite as `800-63B-4 §3.1.1.2`. "
        "ASVS V6-V7 give the per-application verification requirements; when both apply, satisfy both.",
        "",
        md,
    ]
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {numbered} numbered headings, {shall} SHALL statements", file=sys.stderr)


if __name__ == "__main__":
    main()
