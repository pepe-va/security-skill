#!/usr/bin/env python3
"""Generate the MITRE ATLAS references from the official YAML (format v6).

Outputs:
  references/standards/mitre-atlas.md                tactics, techniques and mitigations
  references/standards/mitre-atlas-case-studies.md   case studies (real incidents)
"""
import pathlib, re, sys, yaml

SITE = "https://atlas.mitre.org/"
RAW = ("https://raw.githubusercontent.com/mitre-atlas/atlas-data/main/dist/v6/"
       "ATLAS-2026.09.yaml")
ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
SRC = SOURCES / "atlas-2026.09.yaml"
OUT_MAIN = SKILL / "references" / "standards" / "mitre-atlas.md"
OUT_CASES = SKILL / "references" / "standards" / "mitre-atlas-case-studies.md"


def clean(text):
    """Normalise source markdown into a block quote with absolute links."""
    if not text:
        return ""
    # The source uses site-relative links (/techniques/..., /tactics/...).
    text = re.sub(r"\]\(/(techniques|tactics|mitigations|studies)/", r"](" + SITE + r"\1/", text)
    lines = [ln.rstrip() for ln in text.strip().splitlines()]
    return "\n".join("> " + ln if ln else ">" for ln in lines)


def load():
    d = yaml.safe_load(SRC.open(encoding="utf-8"))
    rel = d["relationships"]
    edges = {"achieves": [], "specializes": [], "mitigates": [], "employs": [], "sequences": []}
    for groups in rel.values():
        for rtype, items in groups.items():
            edges[rtype].extend(items)
    return d, edges


def main():
    d, edges = load()
    col = d["collection"]
    tactics, techs, mits, cases = d["tactics"], d["techniques"], d["mitigations"], d["case-studies"]

    order = sorted((e["position"], e["target"]) for e in edges["sequences"])
    tactic_order = [t for _, t in order]

    tac_of = {}            # technique -> [tactics]
    for e in edges["achieves"]:
        tac_of.setdefault(e["source"], []).append(e["target"])
    parent_of = {e["source"]: e["target"] for e in edges["specializes"]}
    subs_of = {}
    for s, p in parent_of.items():
        subs_of.setdefault(p, []).append(s)
    mits_of = {}           # technique -> [(mitigation, use)]
    for e in edges["mitigates"]:
        mits_of.setdefault(e["target"], []).append((e["source"], e.get("description", "")))
    techs_of_mit = {}      # mitigation -> [(technique, use)]
    for e in edges["mitigates"]:
        techs_of_mit.setdefault(e["source"], []).append((e["target"], e.get("description", "")))
    emp_of_case = {}       # case study -> [edge]
    for e in edges["employs"]:
        emp_of_case.setdefault(e["source"], []).append(e)

    parents = [k for k in techs if k not in parent_of]
    tech_by_tactic = {}
    for tid in parents:
        for ta in tac_of.get(tid, []):
            tech_by_tactic.setdefault(ta, []).append(tid)

    # ---------------- main document ----------------
    L = []
    w = L.append
    w("# MITRE ATLAS — adversary tactics, techniques and mitigations against AI systems")
    w("")
    w(f"**Official source:** {SITE}")
    w("")
    w(f"**Dataset:** {RAW}")
    w("")
    w(f"**Release:** {col['version']} · **format-version:** {d['format-version']} · "
      f"**modified-date:** {col['modified-date']}")
    w("")
    w(f"**Contents:** {len(tactics)} tactics · {len(parents)} parent techniques and "
      f"{len(parent_of)} sub-techniques ({len(techs)} objects) · {len(mits)} mitigations · "
      f"{len(cases)} case studies (in `mitre-atlas-case-studies.md`)")
    w("")
    w("> Generated by `scripts/gen_atlas.py` from the official YAML. Do not edit by hand: regenerate.")
    w("")
    w("## Purpose in this skill")
    w("")
    w("ATLAS is not a control catalogue: it is a **taxonomy of adversary behaviour** against AI systems, "
      "structured like MITRE ATT&CK. This skill uses it as:")
    w("")
    w("1. **Threat view** while threat modelling a system with AI: what an adversary may try, in which "
      "order and against which part of the system.")
    w("2. **Common language for findings**: every offensive or red-teaming finding on AI is tagged with "
      "its `AML.T****` so that it is comparable and traceable.")
    w("3. **Bridge to controls**: each technique links its `AML.M****` mitigations, which connect to the "
      "controls of OWASP ASVS, NIST SSDF and the Top 10 for LLM Applications.")
    w("")
    w("## Reading rules")
    w("")
    w("- A technique can **achieve several tactics** (`achieves`); there is no single column per technique.")
    w("- A sub-technique `AML.T****.***` **specialises** its parent (`specializes`) and inherits its "
      "context; assess it together with the parent, not in isolation.")
    w("- `maturity` is the degree of real-world evidence for the technique and is **not** a severity. "
      "This skill never derives severity from ATLAS.")
    w("- `platforms` bounds which kind of system the technique applies to. If no listed platform matches "
      "the system under assessment, the technique is **NOT APPLICABLE**.")
    w("- An ATLAS mitigation describes a **direction of defence**, not a verifiable compliance criterion. "
      "PASS / FAIL must rest on the control of the matching standard (ASVS, SSDF, 800-218A, LLM Top 10).")
    w("- `ATT&CK reference`, when present, links the equivalent MITRE ATT&CK Enterprise technique.")
    w("")
    w("## Tactic index (matrix order)")
    w("")
    for ta in tactic_order:
        n = len(tech_by_tactic.get(ta, []))
        w(f"- **{ta} — {tactics[ta]['name']}** ({n} parent techniques)")
    w("")

    w("## Tactics")
    w("")
    for ta in tactic_order:
        t = tactics[ta]
        w(f"### {ta} — {t['name']}")
        w("")
        w(clean(t["description"]))
        w("")
        lst = sorted(tech_by_tactic.get(ta, []))
        w(f"**Parent techniques that achieve this tactic ({len(lst)}):**")
        w("")
        for tid in lst:
            w(f"- `{tid}` {techs[tid]['name']}")
        w("")

    w("## Techniques")
    w("")
    for tid in sorted(parents):
        t = techs[tid]
        w(f"### {tid} — {t['name']}")
        w("")
        meta = [f"**Tactics:** " + ", ".join(f"`{x}` {tactics[x]['name']}"
                                              for x in sorted(tac_of.get(tid, []))) or "**Tactics:** —"]
        if t.get("platforms"):
            meta.append("**Platforms:** " + ", ".join(t["platforms"]))
        if t.get("maturity"):
            meta.append(f"**Maturity:** {t['maturity']}")
        ar = t.get("attack-reference")
        if ar:
            meta.append(f"**ATT&CK:** [{ar.get('id')}]({ar.get('url')})")
        w("  \n".join(meta))
        w("")
        w(clean(t["description"]))
        w("")
        for sid in sorted(subs_of.get(tid, [])):
            s = techs[sid]
            w(f"#### {sid} — {s['name']}")
            w("")
            sm = []
            if s.get("platforms"):
                sm.append("**Platforms:** " + ", ".join(s["platforms"]))
            if s.get("maturity"):
                sm.append(f"**Maturity:** {s['maturity']}")
            sar = s.get("attack-reference")
            if sar:
                sm.append(f"**ATT&CK:** [{sar.get('id')}]({sar.get('url')})")
            if sm:
                w("  \n".join(sm))
                w("")
            w(clean(s["description"]))
            w("")
        applicable = sorted({m for m, _ in mits_of.get(tid, [])} |
                            {m for sid in subs_of.get(tid, []) for m, _ in mits_of.get(sid, [])})
        if applicable:
            w("**Applicable ATLAS mitigations:** " +
              ", ".join(f"`{m}` {mits[m]['name']}" for m in applicable))
            w("")

    w("## Mitigations")
    w("")
    for mid in sorted(mits):
        m = mits[mid]
        w(f"### {mid} — {m['name']}")
        w("")
        meta = []
        if m.get("categories"):
            meta.append("**Categories:** " + ", ".join(m["categories"]))
        if m.get("lifecycle-phases"):
            meta.append("**Lifecycle phases:** " + ", ".join(m["lifecycle-phases"]))
        if meta:
            w("  \n".join(meta))
            w("")
        w(clean(m["description"]))
        w("")
        pairs = sorted(techs_of_mit.get(mid, []))
        w(f"**Techniques it mitigates ({len(pairs)}):**")
        w("")
        for tid, use in pairs:
            name = techs.get(tid, {}).get("name", "?")
            use = " ".join((use or "").split())
            w(f"- `{tid}` {name}" + (f" — {use}" if use else ""))
        w("")

    OUT_MAIN.parent.mkdir(parents=True, exist_ok=True)
    OUT_MAIN.write_text("\n".join(L) + "\n", encoding="utf-8")

    # ---------------- case studies ----------------
    C = []
    w = C.append
    w("# MITRE ATLAS — case studies")
    w("")
    w(f"**Official source:** {SITE}studies")
    w("")
    w(f"**Release:** {col['version']} · **format-version:** {d['format-version']} · "
      f"{len(cases)} cases")
    w("")
    w("> Generated by `scripts/gen_atlas.py`. Real incidents and exercises documented by MITRE. They serve "
      "as **evidence of plausibility** for a technique during threat modelling, never as a compliance "
      "criterion.")
    w("")
    for cid in sorted(cases):
        c = cases[cid]
        w(f"## {cid} — {c['name']}")
        w("")
        meta = []
        if c.get("incident-date"):
            meta.append(f"**Date:** {c['incident-date']}")
        if c.get("case-study-type"):
            meta.append(f"**Type:** {c['case-study-type']}")
        if c.get("actor"):
            meta.append(f"**Actor:** {c['actor']}")
        if c.get("target"):
            meta.append(f"**Target:** {c['target']}")
        if meta:
            w("  \n".join(meta))
            w("")
        w(clean(c.get("summary", "")))
        w("")
        steps = emp_of_case.get(cid, [])
        if steps:
            w(f"**Techniques used ({len(steps)}):**")
            w("")
            for e in steps:
                tid = e["target"]
                name = techs.get(tid, {}).get("name", "?")
                ta = e.get("tactic")
                tn = f" [{ta} {tactics[ta]['name']}]" if ta in tactics else ""
                w(f"- `{tid}` {name}{tn}")
            w("")
    OUT_CASES.write_text("\n".join(C) + "\n", encoding="utf-8")

    print(f"{OUT_MAIN.name}: {len(tactics)} tactics, {len(parents)} parent techniques, "
          f"{len(parent_of)} sub-techniques, {len(mits)} mitigations", file=sys.stderr)
    print(f"{OUT_CASES.name}: {len(cases)} case studies", file=sys.stderr)


if __name__ == "__main__":
    main()
