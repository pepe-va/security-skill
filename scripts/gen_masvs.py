#!/usr/bin/env python3
"""Generate references/standards/owasp-masvs.md from the official OWASP MASVS release YAML.

Source: OWASP_MASVS.yaml, asset of the latest MASVS release (fetch_sources.py, group "masvs").
Requires pyyaml.
"""
import pathlib, re, sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
SRC = SOURCES / "masvs" / "OWASP_MASVS-2.1.0.yaml"
OUT = SKILL / "references" / "standards" / "owasp-masvs.md"


def main():
    d = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    meta, groups = d["metadata"], d["groups"]
    version = meta.get("version", "2.1.0")
    controls = [c for g in groups for c in g["controls"]]

    L = []
    w = L.append
    w(f"# OWASP MASVS {version} — Mobile Application Security Verification Standard")
    w("")
    w("**Official source:** https://mas.owasp.org/MASVS/ · **Release data:** "
      f"https://github.com/OWASP/masvs/releases (OWASP_MASVS.yaml) · **Licence:** {meta.get('license', 'CC BY-SA 4.0')}")
    w("")
    w(f"**Contents:** {len(groups)} control groups · {len(controls)} controls.")
    w("")
    w("> Generated by `scripts/gen_masvs.py` from the official release YAML; statements and descriptions are verbatim. "
      "Do not edit by hand: regenerate.")
    w("")
    w("## Purpose in this skill")
    w("")
    w("MASVS is the **verifiable standard for mobile apps**, the mobile counterpart of ASVS. Use it for any iOS or "
      "Android client: storage, cryptography, authentication, network, platform interaction, code quality, "
      "resilience and privacy. Cite controls as `MASVS-STORAGE-1 (MASVS 2.1.0)`. The test procedures live in the "
      "OWASP MASTG (tier B in `INVENTORY.md`). MASVS-RESILIENCE controls are defence in depth: their absence alone "
      "is a hardening note, not a vulnerability, unless a real boundary is crossed.")
    w("")
    w("## Index")
    w("")
    for g in groups:
        w(f"- **{g['id']} — {g['title']}**: " + ", ".join(c["id"] for c in g["controls"]))
    w("")
    for g in groups:
        w(f"## {g['id']} — {g['title']}")
        w("")
        w(re.sub(r"\n{3,}", "\n\n", (g.get("description") or "").strip()))
        w("")
        for c in g["controls"]:
            w(f"### {c['id']}")
            w("")
            w(f"> {c['statement'].strip()}")
            w("")
            w(re.sub(r"\n{3,}", "\n\n", (c.get("description") or "").strip()))
            w("")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{OUT.name}: MASVS {version}, {len(groups)} groups, {len(controls)} controls", file=sys.stderr)


if __name__ == "__main__":
    main()
