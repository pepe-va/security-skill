#!/usr/bin/env python3
"""Generate references/standards/cvss-4.0.md from FIRST's CVSS v4.0 specification page.

Keeps the normative part of the specification — Nomenclature, the Base, Threat, Environmental and
Supplemental metric definitions (Tables 1-21), the qualitative severity scale (Table 22) and the
vector string rules (Table 23) — and drops the scoring-design narrative, which scripts/cvss4.py
implements. Requires beautifulsoup4, lxml and markdownify.
"""
import pathlib, re, sys

from bs4 import BeautifulSoup
from markdownify import markdownify

ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
SRC = SOURCES / "cvss" / "specification-document.html"
OUT = SKILL / "references" / "standards" / "cvss-4.0.md"
URL = "https://www.first.org/cvss/v4.0/specification-document"
KEEP_FROM = "Nomenclature"
STOP_AT = "CVSS v4.0 Scoring"


def main():
    soup = BeautifulSoup(SRC.read_text(encoding="utf-8"), "lxml")
    for tag in soup.select("script, style, nav, header, footer"):
        tag.decompose()
    start = next(h for h in soup.find_all(["h1", "h2"]) if h.get_text(" ", strip=True) == KEEP_FROM)
    stop = next(h for h in soup.find_all("h1") if h.get_text(" ", strip=True) == STOP_AT)
    chunks, node = [], start
    while node is not None and node is not stop:
        if getattr(node, "name", None):
            chunks.append(str(node))
        node = node.next_sibling
    html = "".join(chunks)
    if "Table 23" not in html:
        # The headings sit in nested containers on some page versions: fall back to a document slice.
        page = str(soup)
        html = page[page.index(str(start)): page.index(str(stop))]
    md = markdownify(html, heading_style="ATX", bullets="-")
    md = re.sub(r"^(#{1,4}) ", lambda m: "#" * (len(m.group(1)) + 1) + " ", md, flags=re.M)
    md = re.sub(r"\n{3,}", "\n\n", md).strip()
    tables = len(re.findall(r"Table \d+:", md))

    L = [
        "# CVSS v4.0 — Common Vulnerability Scoring System",
        "",
        f"**Official source:** {URL} · **Publisher:** FIRST.Org, Inc. (CVSS Special Interest Group)",
        "",
        "> Generated by `scripts/gen_cvss.py` from the specification page: Nomenclature, metric definitions, "
        "qualitative severity scale and vector string rules, verbatim. The scoring algorithm itself "
        "(MacroVectors and interpolation) is implemented by `scripts/cvss4.py`, a port of FIRST's reference "
        "calculator. CVSS is owned and managed by FIRST; see the source page for its terms. Do not edit by hand: "
        "regenerate.",
        "",
        "## How this skill uses CVSS",
        "",
        "- **Never estimate a score.** Write the vector, then run `python scripts/cvss4.py \"<vector>\"`; it returns "
        "score, qualitative severity, nomenclature (`CVSS-B`, `CVSS-BT`, `CVSS-BE`, `CVSS-BTE`) and MacroVector. "
        "It rejects vectors whose metrics are out of the order of Table 23, as the specification requires.",
        "- **Only `confirmed` findings get a CVSS vector**, and the vector describes what was demonstrated, not the "
        "worst case one could imagine. `needs_validation` findings carry no severity and no CVSS.",
        "- **The finding's overall severity is not the CVSS score.** It follows the severity anchors in "
        "`../audit/README.md` (demonstrated impact, likelihood, blast radius). CVSS is the standard, comparable "
        "supplement; if both disagree, explain why in the finding.",
        "- Report the nomenclature with the score (`CVSS-B 9.3`). A Base-only score says nothing about threat or "
        "environment. Unset Threat/Environmental metrics count as their worst case.",
        "",
    ]
    L.append(md)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    # cvss4.py reads FIRST's lookup tables at runtime: ship them inside the skill.
    calc = SKILL / "assets" / "cvss-calculator"
    calc.mkdir(parents=True, exist_ok=True)
    tables = sorted((SOURCES / "cvss" / "calculator").glob("*.js"))
    for js in tables:
        (calc / js.name).write_bytes(js.read_bytes())
    (calc / "README.md").write_text(
        "# FIRST CVSS v4.0 calculator tables\n\n"
        "Copied by `scripts/gen_cvss.py` from https://github.com/FIRSTdotorg/cvss-v4-calculator "
        "(BSD-2-Clause; copyright FIRST, Red Hat, and contributors, as stated in each file). "
        "`../../scripts/cvss4.py` reads them to compute scores; nothing here is executed.\n", encoding="utf-8")
    print(f"{OUT.name}: {tables} specification tables", file=sys.stderr)


if __name__ == "__main__":
    main()
