#!/usr/bin/env python3
"""Generate references/standards/owasp-api-top10-2023.md from the official OWASP API Security markdown.

Source: editions/2023/en/ of OWASP/API-Security (fetch_sources.py, group "api-top10"). The ten risk
pages are reproduced verbatim; links that pointed at sibling files are rewritten to in-file anchors.

Stdlib only.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
SRC = SOURCES / "api-top10-2023"
OUT = SKILL / "references" / "standards" / "owasp-api-top10-2023.md"
SITE = "https://owasp.org/API-Security/editions/2023/en/0x11-t10/"
REPO = "https://github.com/OWASP/API-Security/tree/master/editions/2023/en"
RISKS = ["0xa1-broken-object-level-authorization.md", "0xa2-broken-authentication.md",
         "0xa3-broken-object-property-level-authorization.md", "0xa4-unrestricted-resource-consumption.md",
         "0xa5-broken-function-level-authorization.md", "0xa6-unrestricted-access-to-sensitive-business-flows.md",
         "0xa7-server-side-request-forgery.md", "0xa8-security-misconfiguration.md",
         "0xa9-improper-inventory-management.md", "0xaa-unsafe-consumption-of-apis.md"]


def anchor(title):
    return re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")


def main():
    titles = {f: (SRC / f).read_text(encoding="utf-8").splitlines()[0].lstrip("# ").strip() for f in RISKS}

    def relink(md):
        for f, t in titles.items():
            md = md.replace(f"]({f})", f"](#{anchor(t)})").replace(f"]: {f}", f"]: #{anchor(t)}")
        md = re.sub(r"\]\((0x[0-9a-f]{2}-[a-z0-9-]+)\.md\)", r"](https://owasp.org/API-Security/editions/2023/en/\1/)", md)
        return re.sub(r"\]: (0x[0-9a-f]{2}-[a-z0-9-]+)\.md", r"]: https://owasp.org/API-Security/editions/2023/en/\1/", md)

    L = []
    w = L.append
    w("# OWASP API Security Top 10 — 2023")
    w("")
    w(f"**Official source:** {SITE} · **Source text:** {REPO} · **Licence:** CC BY-SA 4.0")
    w("")
    w("> Generated by `scripts/gen_api_top10.py` from the official markdown; the ten risk pages are verbatim. Do not "
      "edit by hand: regenerate.")
    w("")
    w("## Purpose in this skill")
    w("")
    w("The API Top 10 is an **awareness list for APIs**, like the OWASP Top 10 is for web applications. Use it to "
      "steer an API review (BOLA, BOPLA and function-level authorisation are the classic API failures) and to name "
      "a finding's API risk (`API1:2023`). PASS / FAIL is issued against the verifiable requirement — ASVS 5.0.0 "
      "(V8 authorisation, V4 web services, V2 business logic) — not against the list itself.")
    w("")
    w(relink(re.sub(r"\A#[^\n]*\n", "## The ten risks\n", (SRC / "0x11-t10.md").read_text(encoding="utf-8").strip())))
    w("")
    for f in RISKS:
        md = (SRC / f).read_text(encoding="utf-8").strip()
        md = re.sub(r"^(#{1,5}) ", lambda m: "#" * (len(m.group(1)) + 1) + " ", md, flags=re.M)
        w(relink(md))
        w("")
        w("---")
        w("")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {len(RISKS)} risks", file=sys.stderr)


if __name__ == "__main__":
    main()
