#!/usr/bin/env python3
"""Generate the NIST SP 800-53 Rev. 5 references from the official OSCAL catalogue.

Source: NIST_SP-800-53_rev5_catalog.json from usnistgov/oscal-content (fetch_sources.py, group "800-53").
Outputs under references/standards/nist-800-53r5/: README.md (families, version, citing rules, withdrawn
controls) and one file per family (ac.md, au.md, ...) with each control's statement, trimmed discussion,
related controls and its enhancements. Organisation-defined parameters are rendered the way the
publication prints them: [Assignment: organization-defined ...] and [Selection: ...]. The 800-53A
assessment parts carried by the same file are left out.

Stdlib only.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
SRC = SOURCES / "nist-800-53" / "NIST_SP-800-53_rev5_catalog.json"
OUT = SKILL / "references" / "standards" / "nist-800-53r5"
REPO = "https://github.com/usnistgov/oscal-content/tree/main/nist.gov/SP800-53/rev5"
DOI = "https://doi.org/10.6028/NIST.SP.800-53r5"


def prop(o, name, cls=None):
    for p in o.get("props", []):
        if p["name"] == name and (cls is None or p.get("class") == cls):
            return p["value"]
    return None


def label(o):
    return next((p["value"] for p in o.get("props", []) if p["name"] == "label" and "class" not in p), o["id"].upper())


def make_render(params):
    def render(text):
        def sub(m):
            p = params.get(m.group(1))
            if not p:
                return m.group(0)
            if "select" in p:
                sel = p["select"]
                how = sel.get("how-many")
                head = "Selection" + (f" ({how.replace('-', ' ')})" if how else "")
                return f"[{head}: " + "; ".join(render(c) for c in sel.get("choice", [])) + "]"
            return f"[Assignment: organization-defined {p.get('label', m.group(1))}]"
        return re.sub(r"\{\{\s*insert:\s*param,\s*([\w.-]+)\s*\}\}", sub, text or "")
    return render


def statement(part, render, depth=0):
    lines = []
    lab = label(part) if prop(part, "label") else ""
    prose = render(part.get("prose", "")).strip()
    if part.get("name") == "item":
        lines.append("  " * max(depth - 1, 0) + f"- {lab} {prose}".rstrip())
    elif prose:
        lines.append(prose)
    for sub in part.get("parts", []):
        lines += statement(sub, render, depth + 1)
    return lines


def trim(t, n):
    t = re.sub(r"\s+", " ", t or "").strip()
    if len(t) <= n:
        return t
    cut = t[:n]
    return cut[: cut.rfind(". ") + 1] if ". " in cut else cut + "…"


def control_block(c, render, w, level, ids_title):
    withdrawn = prop(c, "status") == "withdrawn"
    w(f"{'#' * level} {label(c)} — {c['title']}" + (" · [withdrawn]" if withdrawn else ""))
    w("")
    if withdrawn:
        dest = [l["href"].lstrip("#") for l in c.get("links", []) if l.get("rel") in ("incorporated-into", "moved-to")]
        w("*Withdrawn* — " + (("incorporated into / moved to " + ", ".join(ids_title.get(x, x.upper()) for x in dest))
                              if dest else "no destination given") + ".")
        w("")
        return
    st = next((p for p in c.get("parts", []) if p["name"] == "statement"), None)
    if st:
        w("\n".join(statement(st, render)))
        w("")
    if level == 3:
        g = next((p for p in c.get("parts", []) if p["name"] == "guidance"), None)
        if g:
            w("*Discussion (trimmed):* " + trim(render(g.get("prose", "")), 900))
            w("")
    rel = [ids_title.get(l["href"].lstrip("#"), l["href"].lstrip("#").upper())
           for l in c.get("links", []) if l.get("rel") == "related"]
    if rel and level == 3:
        w("*Related controls:* " + ", ".join(rel))
        w("")


def main():
    cat = json.loads(SRC.read_text(encoding="utf-8"))["catalog"]
    meta = cat["metadata"]
    OUT.mkdir(parents=True, exist_ok=True)
    ids_title, params = {}, {}
    for g in cat["groups"]:
        for c in g["controls"]:
            ids_title[c["id"]] = label(c)
            for p in c.get("params", []):
                params[p["id"]] = p
            for e in c.get("controls", []):
                ids_title[e["id"]] = label(e)
                for p in e.get("params", []):
                    params[p["id"]] = p
    render = make_render(params)
    n_ctl = n_enh = n_wd = 0
    families = []
    for g in cat["groups"]:
        F = []
        w = F.append
        w(f"# NIST SP 800-53 Rev. 5 — {g['id'].upper()}: {g['title']}")
        w("")
        w(f"> Generated by `scripts/gen_800_53.py` from the OSCAL catalogue ({meta.get('version')}). Read `README.md` "
          "for the citing rules. Do not edit by hand: regenerate.")
        w("")
        for c in g["controls"]:
            n_ctl += 1
            n_wd += prop(c, "status") == "withdrawn"
            control_block(c, render, w, 3, ids_title)
            for e in c.get("controls", []):
                n_enh += 1
                n_wd += prop(e, "status") == "withdrawn"
                control_block(e, render, w, 4, ids_title)
        (OUT / f"{g['id']}.md").write_text("\n".join(F) + "\n", encoding="utf-8")
        families.append((g["id"], g["title"], len(g["controls"])))

    R = []
    w = R.append
    w(f"# NIST SP 800-53 Rev. 5 — Security and Privacy Controls for Information Systems and Organizations")
    w("")
    w(f"**Official source:** {DOI} · **Data:** {REPO} (OSCAL, `{meta.get('title')}`, version {meta.get('version')}, "
      f"last modified {meta.get('last-modified', '')[:10]})")
    w("")
    w(f"**Contents:** {len(families)} families · {n_ctl} controls · {n_enh} control enhancements "
      f"({n_wd} of them withdrawn, kept for traceability).")
    w("")
    w("> Generated by `scripts/gen_800_53.py` from the official OSCAL catalogue. Statements are verbatim; discussions "
      "are trimmed; the 800-53A assessment procedures are not reproduced. Do not edit by hand: regenerate.")
    w("")
    w("## Purpose in this skill")
    w("")
    w("800-53 is the **control catalogue** behind CSF 2.0's informative references and FedRAMP, and the most cited "
      "control set in the Anthropic-Cybersecurity-Skills playbooks. Use it when a finding or a programme gap needs a "
      "formal control (`AC-6 Least Privilege`, `SI-10 Information Input Validation`), when the context is federal "
      "or FedRAMP, or to verify crosswalk rows labelled FedRAMP. For application-level verification, ASVS stays "
      "the more precise standard.")
    w("")
    w("## Reading and citing rules")
    w("")
    w("- Cite as `AC-2(4) (SP 800-53 Rev. 5.2.0)`. Enhancements are written `CONTROL(n)`.")
    w("- `[Assignment: organization-defined …]` and `[Selection: …]` are parameters the organisation must set. A "
      "control with unset parameters cannot be PASS: the evidence must show the chosen value.")
    w("- Withdrawn controls stay listed with their destination; never cite them as current.")
    w("- Baselines (low / moderate / high, privacy) are defined in SP 800-53B, which is not reproduced here "
      "(tier B in `../INVENTORY.md`).")
    w("")
    w("## Families")
    w("")
    w("| Family | Title | Controls | File |")
    w("|---|---|---:|---|")
    for fid, title, n in families:
        w(f"| {fid.upper()} | {title} | {n} | `{fid}.md` |")
    w("")
    (OUT / "README.md").write_text("\n".join(R) + "\n", encoding="utf-8")
    print(f"nist-800-53r5/: {meta.get('version')}, {len(families)} families, {n_ctl} controls, {n_enh} enhancements, "
          f"{n_wd} withdrawn", file=sys.stderr)


if __name__ == "__main__":
    main()
