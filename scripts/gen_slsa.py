#!/usr/bin/env python3
"""Generate references/standards/slsa.md from the SLSA v1.2 specification markdown.

Source: docs/spec/v1.2/ at tag v1.2 of slsa-framework/slsa (fetch_sources.py, group "slsa"). The
requirement pages are reproduced verbatim; Jekyll front matter and Liquid tags are removed, HTML
tables are converted to markdown, and links between spec pages are rewritten to slsa.dev.
Requires markdownify.
"""
import pathlib, re, sys

from markdownify import markdownify

ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
SRC = SOURCES / "slsa-1.2"
OUT = SKILL / "references" / "standards" / "slsa.md"
SPEC = "https://slsa.dev/spec/v1.2/"
PAGES = ["tracks.md", "build-track-basics.md", "build-requirements.md", "source-requirements.md",
         "verifying-artifacts.md", "verifying-source.md", "threats-overview.md", "threats.md"]


def clean(md):
    md = re.sub(r"\A---\n.*?\n---\n", "", md, flags=re.S)
    md = re.sub(r"\{%-?.*?-?%\}|\{\{.*?\}\}", "", md, flags=re.S)
    md = re.sub(r"(?s)<table.*?</table>", lambda m: "\n" + markdownify(m.group(0), heading_style="ATX").strip() + "\n", md)
    md = re.sub(r"<!--.*?-->", "", md, flags=re.S)
    md = re.sub(r"\]\(([a-z0-9-]+)\.md(#[^)]*)?\)", lambda m: f"]({SPEC}{m.group(1)}{m.group(2) or ''})", md)
    md = re.sub(r"^\[([^\]]+)\]: ([a-z0-9-]+)\.md(#\S*)?", lambda m: f"[{m.group(1)}]: {SPEC}{m.group(2)}{m.group(3) or ''}", md, flags=re.M)
    md = re.sub(r"^(#{1,5}) ", lambda m: "#" * (len(m.group(1)) + 2) + " ", md, flags=re.M)
    return re.sub(r"\n{3,}", "\n\n", md).strip()


def title(md):
    m = re.search(r'^title:\s*"?(.*?)"?\s*$', md, re.M)
    return m.group(1) if m else "Untitled"


def main():
    L = [
        "# SLSA v1.2 — Supply-chain Levels for Software Artifacts",
        "",
        f"**Official source:** {SPEC} · **Source text:** https://github.com/slsa-framework/slsa/tree/v1.2/docs/spec/v1.2 "
        "· **Licence:** Community Specification License 1.0",
        "",
        "> Generated by `scripts/gen_slsa.py` from the specification markdown at tag v1.2. The pages below are verbatim; "
        "terminology, provenance format and assessment questionnaires are linked, not reproduced. Do not edit by "
        "hand: regenerate.",
        "",
        "## Purpose in this skill",
        "",
        "SLSA states **verifiable levels for build and source integrity**: Build L0-L3 (provenance exists → hosted "
        "build platform → hardened builds) and the Source track. Use it for CI/CD, release and dependency findings "
        "(with SSDF PS.1-PS.3 and PW.4, ASVS V15, A03:2025 and SC-SUP-*), and in mode 3 to judge provenance of "
        "dependencies. Requirements use RFC 2119 keywords (MUST, SHOULD, MAY). Cite as `SLSA v1.2 Build L3`.",
        "",
    ]
    for p in PAGES:
        raw = (SRC / p).read_text(encoding="utf-8")
        L.append(f"## {title(raw)}")
        L.append("")
        L.append(f"*Source page:* {SPEC}{p[:-3]}")
        L.append("")
        L.append(clean(raw))
        L.append("")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {len(PAGES)} specification pages", file=sys.stderr)


if __name__ == "__main__":
    main()
