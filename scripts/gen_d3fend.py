#!/usr/bin/env python3
"""Generate references/standards/mitre-d3fend.md from the official D3FEND ontology (JSON-LD).

Each defensive technique (D3-*) gets its tactic, parent, definition and the digital artifacts it acts
on. The ATT&CK techniques "acting on the same artifacts" are DERIVED here: an offensive technique is
listed when one of its artifacts is the defended artifact or a subclass of it. This approximates the
inferred mappings shown on d3fend.mitre.org; it is a navigation aid, not an official mapping.

Stdlib only.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
SRC = SOURCES / "d3fend" / "d3fend.json"
OUT = SKILL / "references" / "standards" / "mitre-d3fend.md"
TACTICS = ["Model", "Harden", "Detect", "Isolate", "Deceive", "Evict", "Restore"]
SKIP_PROPS = {"d3f:d3fend-id", "d3f:definition", "d3f:kb-article", "d3f:kb-reference", "d3f:synonym",
              "d3f:enables", "d3f:display-order", "d3f:attack-id", "d3f:release-date"}
MAX_RELATED = 30


def ids(v):
    if v is None:
        return []
    v = v if isinstance(v, list) else [v]
    return [x["@id"] for x in v if isinstance(x, dict) and "@id" in x]


def label(n):
    lab = n.get("rdfs:label")
    if isinstance(lab, list):
        lab = lab[0]
    if isinstance(lab, dict):
        lab = lab.get("@value")
    return lab or n["@id"].split(":", 1)[-1]


def text(v):
    if isinstance(v, list):
        v = v[0]
    if isinstance(v, dict):
        v = v.get("@value", "")
    return re.sub(r"\s+", " ", v or "").strip()


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))
    g = data["@graph"]
    by = {n["@id"]: n for n in g}
    onto = next(n for n in g if "owl:Ontology" in (n.get("@type") if isinstance(n.get("@type"), list) else [n.get("@type")]))
    release = text(onto.get("d3f:release-date"))[:10]
    version = text(onto.get("owl:versionInfo")) or release

    parents = {n["@id"]: [p for p in ids(n.get("rdfs:subClassOf")) if not p.startswith("_:")] for n in g}

    def relations(n):
        """(property, target class) pairs, direct or inside owl:Restriction blank nodes."""
        out = []
        for k, v in n.items():
            if k.startswith("d3f:") and k not in SKIP_PROPS:
                out += [(k[4:], t) for t in ids(v) if not t.startswith("_:")]
        for b in ids(n.get("rdfs:subClassOf")):
            r = by.get(b)
            if r and ids(r.get("owl:onProperty")):
                prop = ids(r.get("owl:onProperty"))[0]
                for t in ids(r.get("owl:someValuesFrom")) + ids(r.get("owl:allValuesFrom")):
                    if prop.startswith("d3f:") and not t.startswith("_:"):
                        out.append((prop[4:], t))
        return out

    def ancestors(c, seen=None):
        seen = seen if seen is not None else set()
        for p in parents.get(c, []):
            if p not in seen:
                seen.add(p)
                ancestors(p, seen)
        return seen

    defs = {n["@id"]: n for n in g if str(n.get("d3f:d3fend-id", "")).startswith("D3-")}
    def tactic_of(c):
        for x in [c] + sorted(ancestors(c)):
            for t in ids(by.get(x, {}).get("d3f:enables")):
                name = t.split(":", 1)[-1]
                if name in TACTICS:
                    return name
        return "—"

    attack = {n["@id"]: n for n in g if re.fullmatch(r"T\d{4}(\.\d{3})?", str(n.get("d3f:attack-id", "")))}
    off_artifacts = {}
    for oid, o in attack.items():
        arts = {t for _, t in relations(o) if t in by}
        off_artifacts[oid] = arts

    def related_attack(dnode):
        arts = {t for _, t in relations(dnode) if t in by and t not in defs}
        if not arts:
            return []
        hits = []
        for oid, oarts in off_artifacts.items():
            if any(a in arts or arts & ancestors(a) for a in oarts):
                hits.append(attack[oid]["d3f:attack-id"])
        return sorted(set(hits), key=lambda x: [int(p) for p in re.findall(r"\d+", x)])

    by_tactic = {t: [] for t in TACTICS + ["—"]}
    for c, n in defs.items():
        by_tactic[tactic_of(c)].append(c)

    L = []
    w = L.append
    w("# MITRE D3FEND — cybersecurity countermeasure knowledge graph")
    w("")
    w(f"**Official source:** https://d3fend.mitre.org/ · **Ontology:** https://d3fend.mitre.org/ontologies/d3fend.json "
      f"(release {release}{'' if version == release else ', version ' + version}) · **Licence:** {text(onto.get('dcterms:license')) or 'see source'}")
    w("")
    w(f"**Contents:** {len(TACTICS)} tactics · {len(defs)} defensive techniques (`D3-*`).")
    w("")
    w("> Generated by `scripts/gen_d3fend.py` from the official ontology. Do not edit by hand: regenerate. "
      "*Related ATT&CK techniques* are **derived** by this generator from shared digital artifacts (an offensive "
      "technique whose artifact is the defended artifact or a subclass of it). They approximate the inferred "
      "mappings on d3fend.mitre.org and are a navigation aid, not an official mapping.")
    w("")
    w("## Purpose in this skill")
    w("")
    w("D3FEND names **countermeasures**. Use it to phrase the defensive side of a finding or a threat model in a "
      "standard vocabulary (`D3-MFA Multi-factor Authentication`) and to go from an ATT&CK technique to candidate "
      "countermeasures. Like ATT&CK mitigations, a D3FEND technique is a direction of defence, not a compliance "
      "criterion: PASS / FAIL rests on the verifiable control (ASVS, SSDF, 800-53, CSF 2.0). Playbooks from "
      "Anthropic-Cybersecurity-Skills cite D3FEND techniques **by name**; search this file by label.")
    w("")
    w("## Tactics")
    w("")
    for t in TACTICS + ["—"]:
        members = sorted(by_tactic[t], key=lambda c: label(defs[c]))
        if not members:
            continue
        w(f"- **{t}** ({len(members)}): " + ", ".join(f"{defs[c]['d3f:d3fend-id']} {label(defs[c])}" for c in members))
    w("")
    w("## Techniques")
    w("")
    for c in sorted(defs, key=lambda c: (TACTICS.index(tactic_of(c)) if tactic_of(c) in TACTICS else 99, label(defs[c]))):
        n = defs[c]
        w(f"### {n['d3f:d3fend-id']} — {label(n)}")
        w("")
        par = [label(by[p]) for p in parents.get(c, []) if p in by and p in defs]
        meta = [f"**Tactic:** {tactic_of(c)}"]
        if par:
            meta.append("**Parent:** " + ", ".join(par))
        syn = n.get("d3f:synonym")
        if syn:
            meta.append("**Synonyms:** " + ", ".join(text(s) for s in (syn if isinstance(syn, list) else [syn])))
        w(" · ".join(meta) + f" · https://d3fend.mitre.org/technique/{c}/")
        w("")
        if n.get("d3f:definition"):
            w("> " + text(n["d3f:definition"]))
            w("")
        rels = sorted({(p, label(by[t])) for p, t in relations(n) if t in by and t not in defs})
        if rels:
            w("**Acts on:** " + "; ".join(f"{p} {a}" for p, a in rels))
            w("")
        rel = related_attack(n)
        if rel:
            more = f" … (+{len(rel) - MAX_RELATED} more)" if len(rel) > MAX_RELATED else ""
            w("**Related ATT&CK (derived):** " + ", ".join(rel[:MAX_RELATED]) + more)
            w("")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{OUT.name}: release {release}, {len(defs)} defensive techniques", file=sys.stderr)


if __name__ == "__main__":
    main()
