#!/usr/bin/env python3
"""Generate references/standards/owasp-asvs-5.0.0.md from the official ASVS 5.0.0 CSV."""
import csv, pathlib, sys

CSV = "https://raw.githubusercontent.com/OWASP/ASVS/v5.0.0/5.0/docs_en/OWASP_Application_Security_Verification_Standard_5.0.0_en.csv"
ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
SRC = SOURCES / "asvs.csv"
OUT = SKILL / "references" / "standards" / "owasp-asvs-5.0.0.md"


def main():
    rows = list(csv.DictReader(SRC.open(encoding="utf-8")))
    chapters = {}
    for r in rows:
        ch = chapters.setdefault((r["chapter_id"], r["chapter_name"]), {})
        ch.setdefault((r["section_id"], r["section_name"]), []).append(r)

    L = []
    w = L.append
    w("# OWASP ASVS 5.0.0 — verifiable requirements catalogue")
    w("")
    w("**Official source (CSV):** " + CSV)
    w("")
    w("**Project:** https://github.com/OWASP/ASVS")
    w("")
    w(f"**Total requirements:** {len(rows)}")
    w("")
    w("> Generated by `scripts/gen_asvs.py` from the official CSV. Do not edit by hand: "
      "regenerate to avoid drifting from the source.")
    w("")
    w("## Interpretation and traceability rules")
    w("")
    w("- The CSV column `L` is the **minimum verification level**: an L1 requirement belongs to "
      "levels 1, 2 and 3; an L2 requirement to levels 2 and 3; an L3 requirement to level 3 only.")
    w("- This skill assigns no extra severity to a requirement. It is assessed as **PASS**, "
      "**FAIL**, **NOT APPLICABLE** or **NOT VERIFIED**.")
    w("- Cite requirements in the official versioned form `v5.0.0-<chapter>.<section>.<requirement>`, because "
      "identifiers can change between versions.")
    w("- The requirement text is quoted verbatim and **is the compliance criterion**. No interpretation in "
      "this skill may weaken it.")
    w("")
    w("## Index")
    w("")
    for (cid, cname), secs in chapters.items():
        n = sum(len(v) for v in secs.values())
        w(f"- **{cid} — {cname}** ({n} requirements)")
        for (sid, sname), reqs in secs.items():
            w(f"  - {sid} — {sname} ({len(reqs)})")
    w("")

    for (cid, cname), secs in chapters.items():
        w(f"## {cid} — {cname}")
        w("")
        for (sid, sname), reqs in secs.items():
            w(f"### {sid} — {sname}")
            w("")
            for r in reqs:
                rid = r["req_id"]
                ref = "v5.0.0-" + rid.lstrip("V")
                w(f"#### {ref} (`{rid}`) · minimum level L{r['L']}")
                w("")
                w("> " + r["req_description"].replace("\n", " ").strip())
                w("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {len(rows)} requirements, {len(chapters)} chapters", file=sys.stderr)


if __name__ == "__main__":
    main()
