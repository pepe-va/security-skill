#!/usr/bin/env python3
"""Generate references/standards/owasp-top10-2025.md from the official English pages."""
import pathlib, re, sys, urllib.request

from bs4 import BeautifulSoup
from markdownify import markdownify

BASE = "https://top10.owasp.org/2025/"
SLUGS = [
    ("A01:2025", "Broken Access Control", "A01_2025-Broken_Access_Control"),
    ("A02:2025", "Security Misconfiguration", "A02_2025-Security_Misconfiguration"),
    ("A03:2025", "Software Supply Chain Failures", "A03_2025-Software_Supply_Chain_Failures"),
    ("A04:2025", "Cryptographic Failures", "A04_2025-Cryptographic_Failures"),
    ("A05:2025", "Injection", "A05_2025-Injection"),
    ("A06:2025", "Insecure Design", "A06_2025-Insecure_Design"),
    ("A07:2025", "Authentication Failures", "A07_2025-Authentication_Failures"),
    ("A08:2025", "Software or Data Integrity Failures", "A08_2025-Software_or_Data_Integrity_Failures"),
    ("A09:2025", "Security Logging and Alerting Failures", "A09_2025-Security_Logging_and_Alerting_Failures"),
    ("A10:2025", "Mishandling of Exceptional Conditions", "A10_2025-Mishandling_of_Exceptional_Conditions"),
]
ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
CACHE = SOURCES / "top10-2025-en"
OUT = SKILL / "references" / "standards" / "owasp-top10-2025.md"


def fetch(slug):
    CACHE.mkdir(parents=True, exist_ok=True)
    f = CACHE / (slug + ".html")
    if not f.exists():
        url = BASE + slug + "/"
        req = urllib.request.Request(url, headers={"User-Agent": "cybersec-skill-generator"})
        with urllib.request.urlopen(req, timeout=60) as r:
            f.write_bytes(r.read())
    return f.read_text(encoding="utf-8", errors="replace")


def body_markdown(html):
    soup = BeautifulSoup(html, "lxml")
    art = soup.find("article") or soup.find("main")
    for tag in art.select("nav, script, style, .md-source-file, .headerlink, table"):
        tag.decompose()
    for h in art.find_all(["h1", "h2", "h3", "h4"]):
        # The page body nests under one heading per category.
        h.name = {"h1": "h4", "h2": "h4", "h3": "h4", "h4": "h5"}[h.name]
    md = markdownify(str(art), heading_style="ATX", bullets="-")
    md = re.sub(r"\n{3,}", "\n\n", md).strip()
    # The page h1 duplicates the heading this generator already writes.
    md = re.sub(r"\A#### .*\n+", "", md)
    # Sections that only held a table are empty once the table is removed.
    md = re.sub(r"^#{4,5} .*\n+(?=#{4,5} )", "", md, flags=re.M)
    return md.strip()


def main():
    L = []
    w = L.append
    w("# OWASP Top 10:2025 — web application risk view")
    w("")
    w(f"**Official source:** {BASE}")
    w("")
    w("> Generated by `scripts/gen_owasp_top10_2025.py` from the official English pages. "
      "Do not edit by hand: regenerate. The per-category score tables are omitted.")
    w("")
    w("## Purpose in this skill")
    w("")
    w("The Top 10 is an **awareness** document, not a verifiable standard. This skill uses it as a risk view "
      "that steers the search: each category says what can fail and which preventive measures OWASP "
      "recommends. **PASS / FAIL** is never issued against the Top 10 but against the matching verifiable "
      "control (ASVS for applications, SSDF for the process, LLM Top 10 and ATLAS for AI systems). Each "
      "category lists its mapped CWEs, which is how a finding's CWE leads back to a Top 10 category.")
    w("")
    w("## Index")
    w("")
    for code, name, slug in SLUGS:
        w(f"- **{code} — {name}** · {BASE}{slug}/")
    w("")
    for code, name, slug in SLUGS:
        w(f"## {code} — {name}")
        w("")
        w(f"**Official source:** {BASE}{slug}/")
        w("")
        w(body_markdown(fetch(slug)))
        w("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {len(SLUGS)} categories", file=sys.stderr)


if __name__ == "__main__":
    main()
