#!/usr/bin/env python3
"""Generate references/standards/mitre-f3-1.2.md from the MITRE Fight Fraud Framework STIX bundles.

Sources (fetch_sources.py, group "f3"): f3-stix-v1.2.json (current) and f3-stix-v1.1.json (the version
the Anthropic-Cybersecurity-Skills playbooks map to), from center-for-threat-informed-defense/
fight-fraud-framework. The 1.1 bundle is used only to list identifiers that changed.

Stdlib only.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
SRC = SOURCES / "f3" / "f3-stix-v1.2.json"
OLD = SOURCES / "f3" / "f3-stix-v1.1.json"
OUT = SKILL / "references" / "standards" / "mitre-f3-1.2.md"
REPO = "https://github.com/center-for-threat-informed-defense/fight-fraud-framework"


def eid(o):
    return next((r.get("external_id") for r in o.get("external_references", []) if r.get("external_id")), None)


def key(i):
    return [int(p) if p.isdigit() else p for p in re.split(r"(\d+)", i or "")]


def load(path):
    objs = json.loads(path.read_text(encoding="utf-8"))["objects"]
    live = lambda o: not o.get("revoked") and not o.get("x_mitre_deprecated")
    techs = {o["id"]: o for o in objs if o["type"] == "attack-pattern" and live(o)}
    tactics = {o["id"]: o for o in objs if o["type"] == "x-mitre-tactic"}
    matrix = next(o for o in objs if o["type"] == "x-mitre-matrix")
    col = next(o for o in objs if o["type"] == "x-mitre-collection")
    parent = {r["source_ref"]: r["target_ref"] for r in objs
              if r["type"] == "relationship" and r["relationship_type"] == "subtechnique-of"}
    return col, matrix, tactics, techs, parent


def clean(t, limit):
    t = re.sub(r"\(Citation:[^)]*\)", "", t or "")
    t = re.sub(r"\s+\.", ".", re.sub(r"\s+", " ", t)).strip()
    if len(t) > limit:
        cut = t[:limit]
        t = cut[: cut.rfind(". ") + 1] if ". " in cut else cut + "…"
    return t


def main():
    col, matrix, tactics, techs, parent = load(SRC)
    _, _, _, old_techs, _ = load(OLD) if OLD.exists() else (None, None, None, {}, None)
    ids_now = {eid(t) for t in techs.values()}
    ids_old = {eid(t) for t in old_techs.values()}
    order = [t for t in matrix["tactic_refs"] if t in tactics]
    short = {tactics[t]["x_mitre_shortname"]: tactics[t] for t in order}
    subs = {}
    for s, p in parent.items():
        if s in techs and p in techs:
            subs.setdefault(p, []).append(s)
    tops = [t for t in techs if t not in parent]
    f_count = sum(1 for t in techs.values() if (eid(t) or "").startswith("F"))

    L = []
    w = L.append
    w(f"# MITRE Fight Fraud Framework (F3) {col['name'].split()[-1]}")
    w("")
    w(f"**Official source:** https://ctid.mitre.org/fraud/ · **Data:** {REPO} (`public/f3-stix-v1.2.json`, matrix "
      f"modified {matrix.get('modified', '')[:10]})")
    w("")
    w(f"**Contents:** {len(order)} tactics · {len(tops)} techniques and {len(parent)} sub-techniques "
      f"({f_count} fraud-specific `F` IDs, {len(techs) - f_count} reused ATT&CK `T` IDs).")
    w("")
    w("> Generated by `scripts/gen_f3.py` from the official STIX bundle. Descriptions are trimmed. Do not edit by hand: "
      "regenerate.")
    w("")
    w("## Purpose in this skill")
    w("")
    w("F3 is an ATT&CK-compatible catalogue of **cyber-enabled financial fraud**. ATT&CK stops at "
      "`T1657 Financial Theft`; F3 decomposes how an intrusion becomes a loss with two tactics of its own — "
      "**Positioning (FA0001)** and **Monetization (FA0002)**. Use it when the system moves money or value "
      "(payments, banking, wallets, marketplaces, refunds, loyalty points): to threat-model fraud paths and to tag "
      "findings whose abuse is fraud rather than plain compromise (e.g. a missing step-up on beneficiary changes "
      "maps to `F1005.003 Add Beneficiary`). F3 has no mitigations; the controls come from ASVS (business logic, "
      "V2), 800-63B (authentication), API Top 10 (API6 sensitive business flows) and 800-53.")
    w("")
    w("## Reading rules")
    w("")
    w("- `F####` IDs are fraud-specific; `T####` IDs are ATT&CK techniques reused verbatim inside F3 (see "
      "`mitre-attack/`). F3 redefines several ATT&CK tactics for the fraud context.")
    w("- A technique can serve several tactics; sub-techniques use dot notation (`F1005.003`).")
    w("- F3 carries no severity. Cite with the version: `F1005.003 (F3 1.2)`.")
    if ids_old:
        gone, new = sorted(ids_old - ids_now, key=key), sorted(ids_now - ids_old, key=key)
        w(f"- **Changes from 1.1 (the version the playbooks map):** {len(new)} identifiers added"
          + (f" ({', '.join(new)})" if new else "") + f"; {len(gone)} removed"
          + (f" ({', '.join(gone)})" if gone else "") + ".")
    w("")
    w("## Tactic index")
    w("")
    for ta in order:
        t = tactics[ta]
        mem = sorted((x for x in tops if any(ph["phase_name"] == t["x_mitre_shortname"]
                                              for ph in techs[x].get("kill_chain_phases", []))), key=lambda x: key(eid(techs[x])))
        w(f"- **{eid(t)} {t['name']}** ({len(mem)}): " + ", ".join(f"{eid(techs[x])} {techs[x]['name']}" for x in mem))
    w("")
    w("## Techniques")
    w("")
    for tid in sorted(tops, key=lambda x: key(eid(techs[x]))):
        t = techs[tid]
        tac = [f"{eid(short[ph['phase_name']])} {short[ph['phase_name']]['name']}"
               for ph in t.get("kill_chain_phases", []) if ph["phase_name"] in short]
        w(f"### {eid(t)} — {t['name']}")
        w("")
        w(f"**Tactics:** {', '.join(tac) or '—'}")
        w("")
        w("> " + clean(t.get("description"), 1100))
        w("")
        for sid in sorted(subs.get(tid, []), key=lambda x: key(eid(techs[x]))):
            s = techs[sid]
            w(f"#### {eid(s)} — {s['name']}")
            w("")
            w(clean(s.get("description"), 450))
            w("")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {len(order)} tactics, {len(tops)} techniques, {len(parent)} sub-techniques", file=sys.stderr)


if __name__ == "__main__":
    main()
