#!/usr/bin/env python3
"""Generate the OWASP Top 10 for LLM Applications 2026 references from the official markdown.

Source: the English markdown of the 2026 release in GenAI-Security-Project/GenAI-Security-Advisor
(corpus/llm-top10/2026/), fetched by fetch_sources.py. The text is reproduced verbatim; figures are
replaced by their caption because the image files are not part of the corpus.

Outputs:
  references/standards/owasp-llm-top10-2026.md            the ten risks, preface and appendices B/AISVS
  references/standards/owasp-llm-top10-2026-mappings.md   Appendix A, by risk (derived) and by framework (verbatim)

Stdlib only.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
SRC = SOURCES / "llm-top10-2026"
OUT = SKILL / "references" / "standards" / "owasp-llm-top10-2026.md"
OUT_MAP = SKILL / "references" / "standards" / "owasp-llm-top10-2026-mappings.md"
SITE = "https://genai.owasp.org"
RESOURCE = "https://genai.owasp.org/resource/owasp-genai-llm-top-10-2026/"
CORPUS = "https://github.com/GenAI-Security-Project/GenAI-Security-Advisor/tree/main/corpus/llm-top10/2026"
LICENSE = "Creative Commons CC BY-SA 4.0 — https://creativecommons.org/licenses/by-sa/4.0/legalcode"

RISKS = [
    ("LLM01", "LLM01_PromptInjection.md"), ("LLM02", "LLM02_SensitiveInformationDisclosure.md"),
    ("LLM03", "LLM03_ExcessiveAgency.md"), ("LLM04", "LLM04_SupplyChain.md"),
    ("LLM05", "LLM05_DataModelPoisoning.md"), ("LLM06", "LLM06_UnboundedConsumption.md"),
    ("LLM07", "LLM07_Misinformation.md"), ("LLM08", "LLM08_HiddenContextExposure.md"),
    ("LLM09", "LLM09_VectorAndEmbeddingWeaknesses.md"), ("LLM10", "LLM10_ImproperOutputHandling.md"),
]


def read(name):
    return (SRC / name).read_text(encoding="utf-8").strip()


def figures(md):
    """Replace images (not shipped with the corpus) by their alt text."""
    md = re.sub(r"!\[([^\]]*)\]\([^)]*\)", r"*[Figure not reproduced: \1]*", md)
    return re.sub(r'<img [^>]*alt="([^"]*)"[^>]*/?>', r"*[Figure not reproduced: \1]*", md)


def shift(md, levels):
    return re.sub(r"^(#{1,5}) ", lambda m: "#" * (len(m.group(1)) + levels) + " ", md, flags=re.M)


def anchor(title):
    return re.sub(r"[^a-z0-9 -]", "", title.lower()).replace(" ", "-")


def parse_mappings(md):
    """Return {framework_title: [(risk, element, relevance)]} from Appendix A's per-framework tables."""
    out, framework, risk, in_table = {}, None, None, False
    for line in md.splitlines():
        if line.startswith("## "):
            framework, risk, in_table = line[3:].strip(), None, False
            continue
        if re.match(r"^\|\s*Risk\s*\|\s*Element\s*\|\s*Relevance\s*\|", line):
            in_table = True
            continue
        if not line.startswith("|"):
            in_table = False
            continue
        if not framework or not in_table or line.startswith("|---"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3:
            continue
        m = re.search(r"LLM\d\d", cells[0])
        if m:
            risk = m.group(0)
        if risk and cells[1]:
            out.setdefault(framework, []).append((risk, cells[1], cells[2]))
    return out


def main():
    titles = {rid: read(fn).splitlines()[0].lstrip("# ").strip() for rid, fn in RISKS}
    L = []
    w = L.append
    w("# OWASP Top 10 for LLM Applications 2026")
    w("")
    w(f"**Source:** *OWASP Top 10 for LLM Applications 2026*, OWASP GenAI Security Project. Site: {SITE} · "
      f"Resource: {RESOURCE}")
    w("")
    w(f"**Source text:** {CORPUS} — official English markdown of the release.")
    w("")
    w(f"**Source licence:** {LICENSE}")
    w("")
    w("> Generated by `scripts/gen_llm_top10.py`. The ten entries, the preface and the appendices are reproduced "
      "verbatim; figures are replaced by their caption. Sections marked *editorial* are this skill's additions. "
      "Do not edit by hand: regenerate.")
    w("")
    w("## Scope rule (editorial)")
    w("")
    w("This list owns the risk when **the model is a component inside an application**. Once the model becomes "
      "an **actor** — with tools it can call, memory it carries between sessions and consequences it triggers "
      "downstream — the risk moves to the **OWASP Top 10 for Agentic Applications (ASI)** in "
      "`owasp-asi-top10-2026.md`. Many incidents sit on that boundary: read the entry here for the "
      "model-as-component failure and pair it with the agentic list as soon as the model acts on its own. "
      "The preface below states the same boundary in the project leads' words.")
    w("")
    w("For the adversary-behaviour taxonomy that accompanies these risks, see `mitre-atlas.md`.")
    w("")
    w("## How the 2026 ranking was built (editorial summary of the preface)")
    w("")
    w("- The order combines the **community vote (three quarters of the weight)** with the **incident record "
      "(one quarter)**.")
    w("- **Prompt Injection** stays #1 on the vote although the raw incident count would drop it out of the top 10: "
      "a defence effect, not a reason to weigh it less.")
    w("- **Misinformation** was voted near the bottom but the incident record places it near the top: weigh it "
      "more than its position suggests.")
    w("- **Excessive Agency** climbs to third: vote and evidence agree that agentic deployments are where harm lands.")
    w("- **System Prompt Leakage** (2025) is re-scoped as **Hidden Context Exposure**.")
    w("")
    w("## Index")
    w("")
    for i, (rid, _) in enumerate(RISKS, 1):
        w(f"{i}. [{titles[rid]}](#{anchor(titles[rid])})")
    w("")
    w("Mappings to ASI, DSGAI, MITRE ATLAS, MITRE ATT&CK, MITRE CWE, NIST AI 600-1, NIST AI RMF, CSA AICM and "
      "OWASP AIVSS are in `owasp-llm-top10-2026-mappings.md`.")
    w("")
    w("---")
    w("")
    for rid, fn in RISKS:
        w(figures(read(fn)))
        w("")
        w("---")
        w("")
    w("## Preface")
    w("")
    w(shift(figures(read("LLM00_Preface.md")), 1))
    w("")
    w(shift(figures(read("Appendix_B_LLM_Application_Architecture_and_Threat_Modeling.md")), 1))
    w("")
    w(shift(figures(read("LLMZZ_Appendix_AISVS_Mapping.md")), 1))
    w("")
    w("## References")
    w("")
    w(shift(figures(re.sub(r"\A#[^\n]*\n+", "", read("references.md"))), 1))
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")

    appendix = figures(read("Appendix_A_Related_Framework_Mappings.md"))
    mappings = parse_mappings(appendix)
    M = []
    w = M.append
    w("# OWASP Top 10 for LLM Applications 2026 — related framework mappings")
    w("")
    w(f"**Source:** Appendix A of *OWASP Top 10 for LLM Applications 2026* ({CORPUS}). Licence: {LICENSE}")
    w("")
    w("> Generated by `scripts/gen_llm_top10.py`. *Mappings by risk* is derived by regrouping the rows of Appendix A "
      "without changing them; *Appendix A* follows verbatim. Do not edit by hand: regenerate.")
    w("")
    w("**Legend:** ● primary (a central line of defence or description of the risk) · ○ supporting · — no "
      "applicable mapping. Mappings are at each framework's coarse level; the versions they pin (e.g. ATLAS "
      "2026.06, ATT&CK v19.1) can differ from the versions incorporated in this skill — check identifiers "
      "against the local standard files.")
    w("")
    w("## Mappings by risk (derived)")
    w("")
    for rid, _ in RISKS:
        w(f"### {titles[rid]}")
        w("")
        w("| Framework | Element | Relevance |")
        w("|---|---|---|")
        for framework, rows in mappings.items():
            short = re.sub(r"\s*[—(].*$", "", framework).strip()
            for risk, element, relevance in rows:
                if risk == rid:
                    w(f"| {short} | {element} | {relevance} |")
        w("")
    w("## Appendix A (verbatim)")
    w("")
    w(shift(re.sub(r"\A#[^\n]*\n+", "", appendix), 1))
    OUT_MAP.write_text("\n".join(M) + "\n", encoding="utf-8")
    n = sum(len(v) for v in mappings.values())
    print(f"{OUT.name}: {len(RISKS)} risks; {OUT_MAP.name}: {len(mappings)} framework sections, {n} mapping rows",
          file=sys.stderr)


if __name__ == "__main__":
    main()
