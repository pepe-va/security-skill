#!/usr/bin/env python3
"""Generate references/standards/nist-ai-rmf-1.0.md from NIST AI 100-1 and the official AI RMF Playbook.

Sources (fetch_sources.py, group "ai-rmf"):
  sources/ai-rmf/NIST.AI.100-1.pdf   the framework: category statements of the Core (Tables 1-4)
  sources/ai-rmf/playbook.json       the AI RMF Playbook: subcategory statements and suggested actions

Category and subcategory statements are taken from AI 100-1 itself, because the Playbook's
wording of many subcategories differs from the framework (it shortens or expands phrases). The
Playbook supplies only the suggested actions, labelled as such. Checks before writing: 19 categories
and 72 subcategories, the same subcategory IDs in both sources. Category statements that the PDF
table layout cuts are completed from CATEGORY_FIXES, and each fix must appear in the PDF in word order.

Requires pypdf.
"""
import json, pathlib, re, sys

try:
    import pypdf
except ImportError:  # pragma: no cover
    sys.exit("requires pypdf: pip install pypdf")

ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
PDF = SOURCES / "ai-rmf" / "NIST.AI.100-1.pdf"
PLAYBOOK = SOURCES / "ai-rmf" / "playbook.json"
OUT = SKILL / "references" / "standards" / "nist-ai-rmf-1.0.md"
FUNCTIONS = ["GOVERN", "MAP", "MEASURE", "MANAGE"]
SHORT = {"GOVERN": "GV", "MAP": "MP", "MEASURE": "MS", "MANAGE": "MG"}
# Table cells that the PDF text extraction splits; completed here and verified against the PDF.
CATEGORY_FIXES = {"GOVERN 4": "Organizational teams are committed to a culture that considers and communicates AI risk."}


def words(t):
    t = t.replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"')
    return re.findall(r"[a-z0-9]+", t.lower())


def in_order(unit, toks, gap=200):
    pos = {}
    for i, t in enumerate(toks):
        pos.setdefault(t, []).append(i)
    for start in pos.get(unit[0], []):
        i, ok = start, True
        for t in unit[1:]:
            nxt = next((j for j in pos.get(t, []) if i < j <= i + gap), None)
            if nxt is None:
                ok = False
                break
            i = nxt
        if ok:
            return True
    return False


def key(s):
    f, n = s.split(" ")
    return (FUNCTIONS.index(f), [int(x) for x in n.split(".")])


def main():
    raw = "\n".join((p.extract_text() or "") for p in pypdf.PdfReader(str(PDF)).pages)
    flat = re.sub(r"\s+", " ", raw)
    toks = words(flat)

    cats = {}
    for cid, stmt in re.findall(r"((?:GOVERN|MAP|MEASURE|MANAGE) \d+): (.+?)(?= (?:GOVERN|MAP|MEASURE|MANAGE) \d+\.\d+:)", flat):
        cats.setdefault(cid, stmt.strip())
    for cid, fixed in CATEGORY_FIXES.items():
        if not in_order(words(fixed), toks):
            sys.exit(f"category fix for {cid} not found in the PDF in word order")
        cats[cid] = fixed
    if len(cats) != 19:
        sys.exit(f"expected 19 categories, found {len(cats)}")

    items = json.loads(PLAYBOOK.read_text(encoding="utf-8"))
    play = {i["title"].strip(): i for i in items}
    dehyph = re.sub(r"([a-z])- ([a-z])", r"\1\2", flat)
    subs = {}
    marker = r"(?:GOVERN|MAP|MEASURE|MANAGE) \d+(?:\.\d+)?:"
    for sid in play:
        m = re.search(re.escape(sid) + r": (.+?)(?= " + marker + r"| NIST AI 100-1| Table \d| Categories Subcategories|$)", dehyph)
        if not m:
            sys.exit(f"{sid} not found in AI 100-1")
        stmt = m.group(1).strip()
        # Undo a line-break join that swallowed a real hyphen the Playbook keeps (context-specific).
        for a, b in re.findall(r"\b(\w+)- (\w+)", re.sub(r"\s+", " ", flat[flat.find(sid + ":"):flat.find(sid + ":") + 1500])):
            if f"{a}-{b}".lower() in play[sid]["description"].lower():
                stmt = stmt.replace(a + b, f"{a}-{b}")
        stmt = re.sub(r"\b(the|in|of|and)([A-Z]{2,})\b", r"\1 \2", stmt)  # 'theMAP' -> 'the MAP'
        subs[sid] = stmt
    if len(subs) != 72:
        sys.exit(f"expected 72 subcategories, found {len(subs)}")
    differs = sorted((s for s in subs if words(subs[s]) != words(play[s]["description"])), key=key)

    L = []
    w = L.append
    w("# NIST AI Risk Management Framework (AI RMF 1.0)")
    w("")
    w("**Normative source:** NIST AI 100-1, *Artificial Intelligence Risk Management Framework (AI RMF 1.0)* "
      "(January 2023) · https://doi.org/10.6028/NIST.AI.100-1")
    w("")
    w("**Companion:** AI RMF Playbook (suggested actions) · https://airc.nist.gov/airmf-resources/playbook/")
    w("")
    w(f"**Contents:** {len(FUNCTIONS)} functions · {len(cats)} categories · {len(subs)} subcategories, each with the "
      "Playbook's suggested actions.")
    w("")
    w(f"> Generated by `scripts/gen_ai_rmf.py`. Category and subcategory statements come from the Core tables of "
      f"AI 100-1 (the normative text). The Playbook words {len(differs)} of the 72 subcategories differently; its "
      "suggested actions are reproduced, its statements are not. "
      f"{len(CATEGORY_FIXES)} category statement split by the PDF layout was completed and verified in word order. "
      "Do not edit by hand: regenerate.")
    w("")
    w("## Purpose in this skill")
    w("")
    w("AI RMF is the **governance and risk-management view of AI systems**: who decides, what context, how risks are "
      "measured and managed. It complements the technical controls of 800-218A, the LLM Top 10 and ASI, and the "
      "generative-AI actions of `nist-ai-600-1.md`. Use it when the question is organisational (\"do we manage the "
      "risk of this model?\") rather than a code defect.")
    w("")
    w("## Reading rules")
    w("")
    w("- Subcategories are **outcomes**; the framework is voluntary and not a checklist. PASS / FAIL needs "
      "organisational evidence; otherwise report NOT VERIFIED with the evidence that would decide it.")
    w("- **Suggested actions are the Playbook's**, not requirements of AI 100-1. Never present one as mandatory.")
    w("- Cite as `GOVERN 1.1 (AI RMF 1.0)`. Some sources use a short form: `GV-1.1` (crosswalk), `GOVERN-1.1` or "
      "`MEASURE-2.6` (playbook frontmatter); all denote the same subcategory.")
    w("")
    w("## Index")
    w("")
    for f in FUNCTIONS:
        cs = sorted((c for c in cats if c.startswith(f + " ")), key=lambda c: int(c.split()[1]))
        w(f"- **{f} ({SHORT[f]})** — " + " · ".join(f"{c}" for c in cs))
    w("")
    for f in FUNCTIONS:
        w(f"## {f}")
        w("")
        for c in sorted((c for c in cats if c.startswith(f + " ")), key=lambda c: int(c.split()[1])):
            w(f"### {c} — {cats[c]}")
            w("")
            for sid in sorted((s for s in subs if s.startswith(c + ".")), key=key):
                w(f"#### {sid}")
                w("")
                w("> " + subs[sid])
                w("")
                i = play[sid]
                acts = [a.strip(" *-\t") for a in re.split(r"\n\s*[*-]\s+", "\n" + (i.get("section_actions") or "")) if a.strip(" *-\t\n")]
                if acts:
                    w("*Playbook suggested actions:*")
                    w("")
                    for a in acts:
                        w("- " + " ".join(a.split()))
                    w("")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {len(cats)} categories, {len(subs)} subcategories from AI 100-1; "
          f"Playbook wording differs on {len(differs)}", file=sys.stderr)


if __name__ == "__main__":
    main()
