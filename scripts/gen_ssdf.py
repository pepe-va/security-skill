#!/usr/bin/env python3
"""Generate references/standards/nist-ssdf-800-218.md from the NIST CPRT export of SP 800-218 v1.1.

Source: the official machine-readable SSDF 1.1 in NIST's Cybersecurity and Privacy Reference
Tool (CPRT), fetched by fetch_sources.py. The CPRT carries the 4 groups, 19 practices,
42 tasks and their notional implementation examples. It omits the rows that Table 1 of the PDF
keeps for tasks moved between versions; MOVED restores them so old identifiers stay traceable.

Stdlib only.
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent
SOURCES = ROOT.parent / "sources"
SKILL = ROOT.parent / "skills" / "security" / "cybersec-skill"
SRC = SOURCES / "ssdf" / "sp800-218-1.1.0.json"
OUT = SKILL / "references" / "standards" / "nist-ssdf-800-218.md"
CPRT = "https://csrc.nist.gov/extensions/nudp/services/json/nudp/framework/version/sp_800_218_1_1_0/export/json?element=all"
DOI = "https://doi.org/10.6028/NIST.SP.800-218"

# Rows of SP 800-218 Table 1 that record identifiers moved in v1.1 (absent from the CPRT export).
FORMERLY = {"PO.1.3": "PW.3.1", "PW.1.3": "PW.4.3"}
MOVED_PRACTICE = {"PW.3": ("Verify Third-Party Software Complies with Security Requirements", "PW.4")}
MOVED_TASKS = {  # task -> (practice it sat under, where it moved)
    "PW.3.1": ("PW.3", "PO.1.3"),
    "PW.3.2": ("PW.3", "PW.4.4"),
    "PW.4.3": ("PW.4", "PW.1.3"),
    "PW.4.5": ("PW.4", "PW.4.1 and PW.4.4"),
    "PW.5.2": ("PW.5", "PW.5.1 as an example"),
}


def key(ident):
    return [int(p) if p.isdigit() else p for p in ident.replace(".", " ").split()]


def main():
    data = json.loads(SRC.read_text(encoding="utf-8"))["response"]["elements"]
    doc = data["documents"][0]
    els = {e["element_identifier"]: e for e in data["elements"]}
    children = {}
    for r in data["relationships"]:
        if r["relationship_identifier"] != "projection":
            continue
        s, d = els.get(r["source_element_identifier"]), els.get(r["dest_element_identifier"])
        if s and d and d["element_type"] != "sort":
            children.setdefault(s["element_identifier"], []).append(d["element_identifier"])
    groups = [e for e in data["elements"] if e["element_type"] == "group"]
    order = {"PO": 0, "PS": 1, "PW": 2, "RV": 3}
    groups.sort(key=lambda g: order[g["element_identifier"]])

    practices = [e for e in data["elements"] if e["element_type"] == "practice"]
    tasks = [e for e in data["elements"] if e["element_type"] == "task"]
    examples = [e for e in data["elements"] if e["element_type"] == "example"]

    L = []
    w = L.append
    w("# NIST SP 800-218 — Secure Software Development Framework (SSDF) Version 1.1")
    w("")
    w(f"**Normative source:** {doc['name']}, {doc['version'].replace('  ', ' ')} (February 2022).")
    w("")
    w(f"**Official source:** {DOI} · **Machine-readable source (CPRT):** {CPRT}")
    w("")
    w(f"**Contents:** {len(groups)} groups, {len(practices)} practices, {len(tasks)} tasks and {len(examples)} "
      f"notional implementation examples, plus {len(MOVED_TASKS)} rows of tasks moved in v1.1.")
    w("")
    w("> Generated by `scripts/gen_ssdf.py` from the NIST CPRT export. Do not edit by hand: regenerate.")
    w("")
    w("## Reading rules")
    w("")
    w("- Hierarchy: **Practice -> Task -> Notional implementation examples**.")
    w("- The **examples are implementation possibilities**, not mandatory requirements or an exhaustive list. "
      "Never turn an example into an obligation unless another source or the context requires it.")
    w("- The **order** of practices, tasks and examples implies neither implementation sequence nor relative "
      "importance.")
    w("- Where Table 1 records a task as **moved**, the row is kept for historical traceability and points to "
      "its current location.")
    w("- The SSDF is **not a universal checklist**: applicability follows from risk, development context and the "
      "practices that fit the system.")
    w("- For systems that develop, tune, evaluate or integrate generative AI or dual-use foundation models, read the "
      "base task here **together with** its extension in `nist-800-218a.md`.")
    w("")
    w("> **Scope decision of this skill:** Table 1 pairs each task with a long list of informative references "
      "(BSAFSS, BSIMM, EO14028, IEC62443, ISO27034, MSSDL, NISTCSF, OWASPASVS, OWASPSAMM, PCISSLC, SCAGILE, "
      "SCFPSSD, SCSIC, SP80053, SP800160, SP800161, SP800181...). They are omitted here for volume and low "
      "operational value: they map frameworks to each other, they are not compliance criteria. The CPRT export "
      "in `sources/ssdf/` keeps them if a task's cross-references are needed. Practice, task and example "
      "texts are complete.")
    w("")
    w("## Index")
    w("")
    for g in groups:
        gid = g["element_identifier"]
        items = []
        pids = sorted(set(children.get(gid, [])) | {p for p in MOVED_PRACTICE if p.startswith(gid)}, key=key)
        for pid in pids:
            tids = sorted(children.get(pid, []) + [t for t, (p, _) in MOVED_TASKS.items() if p == pid], key=key)
            nums = [t.split(".", 1)[1] for t in tids]
            rng = f"{nums[0]}-{nums[-1]}" if len(nums) > 1 else (nums[0] if nums else "")
            moved = ", moved" if pid in MOVED_PRACTICE else ""
            items.append(f"{pid} ({rng}{moved})")
        w(f"- **{g['title']} ({gid})** — " + " · ".join(items))
    w("")

    for g in groups:
        gid = g["element_identifier"]
        w(f"## {g['title']} ({gid})")
        w("")
        w("> " + g["text"].strip())
        w("")
        pids = sorted(set(children.get(gid, [])) | {p for p in MOVED_PRACTICE if p.startswith(gid)}, key=key)
        for pid in pids:
            if pid in MOVED_PRACTICE:
                title, dest = MOVED_PRACTICE[pid]
                w(f"### {pid} — {title} · [moved to {dest}]")
                w("")
            else:
                p = els[pid]
                w(f"### {pid} — {p['title']}")
                w("")
                w("> " + p["text"].strip())
                w("")
            tids = sorted(children.get(pid, []) + [t for t, (pp, _) in MOVED_TASKS.items() if pp == pid], key=key)
            for tid in tids:
                if tid in MOVED_TASKS:
                    w(f"#### {tid} · [moved to {MOVED_TASKS[tid][1]}]")
                    w("")
                    continue
                t = els[tid]
                suffix = f" · [formerly {FORMERLY[tid]}]" if tid in FORMERLY else ""
                w(f"#### {tid}{suffix}")
                w("")
                w("> " + t["text"].strip())
                w("")
                exs = sorted(children.get(tid, []), key=key)
                if exs:
                    w("**Notional implementation examples**")
                    w("")
                    for i, eid in enumerate(exs, 1):
                        w(f"{i}. " + " ".join(els[eid]["text"].split()))
                    w("")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {len(groups)} groups, {len(practices)} practices, {len(tasks)} tasks, "
          f"{len(examples)} examples, {len(MOVED_TASKS)} moved rows", file=sys.stderr)


if __name__ == "__main__":
    main()
